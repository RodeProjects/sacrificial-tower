"""Compare complete native and Python-reference G-code analysis paths."""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
import tracemalloc
from pathlib import Path
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

import cooling_tower.gcode.native_analysis as native_analysis_module
import cooling_tower.gcode.parser as parser_module
from cooling_tower.services.analysis_service import GCodeAnalysisService


def build_fixture(path: Path, requested_bytes: int) -> None:
    header = (
        "; generated by OrcaSlicer 2.3.0\n"
        "M83\nG90\nM204 S2400\nM205 X8 Y8 Z0.4 E3\n"
    )
    with path.open("w", encoding="utf-8", newline="\n") as output:
        output.write(header)
        written = len(header.encode("utf-8"))
        movement = 0
        layer = 0
        while written < requested_bytes:
            if movement % 8_000 == 0:
                layer += 1
                marker = (
                    f";LAYER:{layer - 1}\n"
                    f"G1 Z{layer * 0.2:.3f} F900\n"
                )
                output.write(marker)
                written += len(marker.encode("utf-8"))
            line = (
                f"G1 X{movement % 173:.3f} "
                f"Y{(movement * 7) % 167:.3f} E0.025 F4200\n"
            )
            output.write(line)
            written += len(line.encode("utf-8"))
            movement += 1


def measure(
    path: Path,
    *,
    native: bool,
    track_python_memory: bool,
) -> tuple[float, int | None, int]:
    if track_python_memory:
        tracemalloc.start()
    started = time.perf_counter()
    try:
        if native:
            service = GCodeAnalysisService()
            snapshot = service.analyze(path, force=True)
            info = service.native_full_analysis_info or {}
            if not info.get("used"):
                raise RuntimeError(f"Native path was not used: {info}")
        else:
            with (
                patch.object(parser_module, "_native_timing", None),
                patch.object(native_analysis_module, "_native_timing", None),
            ):
                snapshot = GCodeAnalysisService().analyze(path, force=True)
        duration = time.perf_counter() - started
        peak = (
            tracemalloc.get_traced_memory()[1]
            if track_python_memory
            else None
        )
    finally:
        if track_python_memory:
            tracemalloc.stop()
    return duration, peak, snapshot.layer_count


def run_benchmark(
    source: Path,
    *,
    runs: int,
    track_python_memory: bool,
) -> dict[str, object]:
    measurements: dict[str, list[dict[str, float | int | None]]] = {
        "native": [],
        "python": [],
    }
    for kind, native in (("native", True), ("python", False)):
        for _ in range(runs):
            duration, peak, layers = measure(
                source,
                native=native,
                track_python_memory=track_python_memory,
            )
            measurements[kind].append(
                {
                    "duration_s": duration,
                    "python_allocator_peak_bytes": peak,
                    "layer_count": layers,
                }
            )
    native_best = min(
        float(item["duration_s"]) for item in measurements["native"]
    )
    python_best = min(
        float(item["duration_s"]) for item in measurements["python"]
    )
    return {
        "source": str(source.resolve()),
        "file_size_bytes": source.stat().st_size,
        "python_memory_tracking": track_python_memory,
        "memory_scope": (
            "Python allocator only; native allocations are not included"
            if track_python_memory
            else "disabled for an unbiased wall-clock comparison"
        ),
        "measurements": measurements,
        "best_speedup_percent": (
            (python_best - native_best) / python_best * 100.0
        ),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--size-mib", type=float, default=18.3)
    parser.add_argument("--runs", type=int, default=2)
    parser.add_argument(
        "--input",
        type=Path,
        help="Read an existing G-code instead of creating a synthetic one.",
    )
    parser.add_argument(
        "--track-python-memory",
        action="store_true",
        help=(
            "Record Python allocator peaks. This adds significant overhead "
            "and does not include native allocations."
        ),
    )
    arguments = parser.parse_args()
    if arguments.size_mib <= 0.0 or arguments.runs < 1:
        parser.error("size-mib and runs must be positive")
    if arguments.input is not None:
        source = arguments.input.expanduser().resolve()
        if not source.is_file():
            parser.error(f"input G-code does not exist: {source}")
        result = run_benchmark(
            source,
            runs=arguments.runs,
            track_python_memory=arguments.track_python_memory,
        )
    else:
        requested_bytes = round(arguments.size_mib * 1024 * 1024)
        with tempfile.TemporaryDirectory(
            prefix="cooling_tower_native_benchmark_"
        ) as temporary:
            source = Path(temporary) / "reference.gcode"
            build_fixture(source, requested_bytes)
            result = run_benchmark(
                source,
                runs=arguments.runs,
                track_python_memory=arguments.track_python_memory,
            )
            result["requested_size_mib"] = arguments.size_mib
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
