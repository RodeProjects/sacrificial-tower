def make_gcode(*, relative=True, relative_xyz=False, layers=6):
    lines = ["; generated by PrusaSlicer 2.9.0", "G21", "G90", "M83" if relative else "M82",
        "M201 X1000 Y1000 Z100 E1000", "M204 S500", "G92 E0", "G1 X100 Y100 Z0.2 F1200"]
    e = 0
    for i in range(layers):
        z = 0.2 * (i + 1)
        lines += [";LAYER_CHANGE", f";Z:{z:.2f}", ";HEIGHT:0.2", f"G1 Z{z:.2f} F1200", "G1 X100 Y100 F6000"]
        if relative_xyz:
            lines += ["G91"]
        previous = (100, 100)
        for x, y in ((110, 100), (110, 110), (100, 110), (100, 100)):
            e += .4
            if relative_xyz:
                dx, dy = x - previous[0], y - previous[1]
                lines.append(f"G1 X{dx} Y{dy} E{.4 if relative else e:.5f} F1200")
            else:
                lines.append(f"G1 X{x} Y{y} E{.4 if relative else e:.5f} F1200")
            previous = (x, y)
        if relative_xyz:
            lines += ["G90"]
    lines += ["G1 E-0.8 F1800" if relative else f"G1 E{e-.8} F1800", "M104 S0", "M140 S0"]
    return "\n".join(lines) + "\n"


class PreprocessorTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.stl = self.root / "model.stl"
        self.stl.write_text("fixture source")
        self.service = PreprocessorService(self.root / "own-temporary")
        self.results = []

    def tearDown(self):
        for result in self.results:
            result.dispose()
        self.temp.cleanup()

    def request(self, text=None, settings=None, adapter="prusa_slicer"):
        source = self.root / "preslice.gcode"
        source.write_text(text or make_gcode(), encoding="utf-8", newline="")
        prepared = PreparedAnalysisSource.capture(source_artifact=SourceArtifact.capture(self.stl),
            analysis_gcode_path=source, gcode_origin=GCodeOrigin.GENERATED_PRESLICE,
            preslice_provenance=PreSliceProvenance.now(duration_s=0, cache_key="a" * 64, adapter_version=1))
        snapshot = GCodeAnalysisService().analyze(source)
        profile = SimpleNamespace(installation=SimpleNamespace(adapter_id=adapter,
            executable_path=self.root / "slicer-installation" / "slicer.exe", profile_roots=(self.root / "slicer-profiles",)),
            effective_values={"bed_shape": ["0x0", "220x0", "220x220", "0x220"], "max_print_height": 250,
                "nozzle_diameter": .4, "filament_diameter": 1.75,
                "extruder_clearance_radius": 12, "extruder_clearance_height": 10}, source_paths=())
        return PreprocessorRequest(prepared, snapshot, profile, settings or PreprocessorSettings())

    def prepare(self, request):
        result = self.service.prepare(request)
        self.results.append(result)
        return result

    def original_movements(self, path, *, strip=False):
        tracker = MachineStateTracker()
        result = []
        inserted = False
        for line in iter_parsed_gcode_lines(path):
            if line.raw_text == BEGIN:
                inserted = True
            event = tracker.process_line(line)
            if isinstance(event, Movement) and not inserted:
                result.append((event.command, event.start_x, event.start_y, event.start_z, event.start_e,
                    event.end_x, event.end_y, event.end_z, event.end_e, event.feedrate_mm_min, event.category))
            if line.raw_text == END:
                inserted = False
        # The printed model stays exact. The shutdown now runs at the wait
        # position, so its non-printing movements are checked separately.
        last_deposit = max(i for i, move in enumerate(result) if move[-1] == "deposition")
        return result[:last_deposit+1]

    def test_four_slicers_preserve_original_bytes_and_machine_movements(self):
        for adapter in SUPPORTED_SLICERS:
            for relative in (True, False):
                with self.subTest(adapter=adapter, relative=relative):
                    request = self.request(make_gcode(relative=relative), adapter=adapter,
                        settings=replace(PreprocessorSettings(), target_layer_time_s=30))
                    original = request.prepared_source.analysis_gcode_path.read_bytes()
                    result = self.prepare(request)
                    self.assertEqual(request.prepared_source.analysis_gcode_path.read_bytes(), original)
                    raw = result.gcode_path.read_bytes().splitlines(keepends=True)
                    retained = []
                    inserted = False
                    for line in raw:
                        if line.strip() == b"; SACRIFICIAL_TOWER_POSTPROCESSED":
                            continue
                        if line.strip() == BEGIN.encode():
                            inserted = True
                        if not inserted:
                            retained.append(line)
                        if line.strip() == END.encode():
                            inserted = False
                    self.assertEqual(b"".join(retained), original)
                    expected = self.original_movements(request.prepared_source.analysis_gcode_path)
                    actual = self.original_movements(result.gcode_path)
                    self.assertEqual(len(actual), len(expected))
                    for a, b in zip(actual, expected):
                        self.assertEqual(a[0], b[0])
                        self.assertEqual(a[-1], b[-1])
                        for x, y in zip(a[1:-1], b[1:-1]):
                            self.assertAlmostEqual(x, y, places=5)
                    self.assertEqual(result.wait_count, sum(wait > 0 for wait in result.layer_waits_s))
                    self.assertGreater(result.wait_count, 0)
                    self.assertLessEqual(result.wait_count, request.snapshot.layer_count)
                    self.assertAlmostEqual(result.height_mm, request.snapshot.layers[-1].z_mm)
                    self.assertTrue(result.scene.tower_segments)
                    self.assertTrue(result.scene.object_segments)

    def test_waits_are_outside_model_and_priming_precedes_return(self):
        request = self.request(settings=replace(PreprocessorSettings(), target_layer_time_s=30))
        result = self.prepare(request)
        tracker = MachineStateTracker()
        waiting = 0
        for line in iter_parsed_gcode_lines(result.gcode_path):
            tracker.process_line(line)
            if line.command == "G4":
                waiting += line.parameters["P"] / 1000
                state = tracker.state
                self.assertFalse(95 < state.x < 115 and 95 < state.y < 115)
                self.assertGreaterEqual(math.dist((state.x, state.y), result.scene.tower_center_xy_mm),
                    result.base_width_mm/2 + request.settings.wait_clearance_mm)
                self.assertAlmostEqual(state.x, result.scene.wait_position_xy_mm[0], places=5)
                self.assertAlmostEqual(state.y, result.scene.wait_position_xy_mm[1], places=5)
                self.assertGreater(state.z, .2)
        self.assertAlmostEqual(waiting, result.total_wait_s, delta=.006)
        self.assertIn("hollow tower", result.gcode_path.read_text())

