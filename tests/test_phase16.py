def source_gcode(*, relative_e: bool = True, layer_count: int = 3) -> str:
    lines = ["; generated by phase16", "G90", "M83" if relative_e else "M82", "M204 S1000"]
    e = 0.0
    for index in range(1, layer_count + 1):
        z = index * 0.2
        lines.append(f"G1 Z{z:.1f} F600")
        e = 1.0 if relative_e else e + 1.0
        lines.append(f"G1 X{10 + index} Y10 E{e:.3f} F600")
    return "\n".join(lines) + "\n"


def tower_gcode(*, layer_count: int = 3, path_size: float = 1.0, feed: float = 60.0) -> str:
    lines = ["; generated tower", "G90", "M83", "M204 S500"]
    for index in range(1, layer_count + 1):
        z = index * 0.2
        lines.extend(
            (
                f"G1 Z{z:.1f} F600",
                f"G1 X0 Y0 E0.01 F{feed:g}",
                f"G1 X{path_size:g} Y0 E0.1 F{feed:g}",
                f"G1 X{path_size:g} Y{path_size:g} E0.1 F{feed:g}",
                f"G1 X0 Y{path_size:g} E0.1 F{feed:g}",
                f"G1 X0 Y0 E0.1 F{feed:g}",
            )
        )
    return "\n".join(lines) + "\n"


class FakeAdapter:
    def __init__(self, gcode: str, *, fail: bool = False, metadata_times=None) -> None:
        self.gcode = gcode
        self.fail = fail
        self.metadata_times = metadata_times
        self.requests = []

    def slice_model(self, request):
        self.requests.append(request)
        if self.fail:
            return SliceResult(False, 2, ("fake",), (), None, (), "", "failed", 0.01, failure_reason="synthetic slicer failure")
        request.output_directory.mkdir(parents=True, exist_ok=True)
        path = request.output_directory / "tower.gcode"
        path.write_text(self.gcode, encoding="utf-8")
        metadata = ()
        if self.metadata_times is not None:
            metadata_path = request.output_directory / "tower.gcode.metadata"
            metadata_path.write_text(json.dumps({"layer_times": self.metadata_times}), encoding="utf-8")
            metadata = (metadata_path,)
        return SliceResult(True, 0, ("fake",), (path,), path, metadata, "ok", "", 0.01)


class SequencedAdapter:
    def __init__(self, outputs: list[str | None]) -> None:
        self.outputs = outputs
        self.requests = []

    def slice_model(self, request):
        self.requests.append(request)
        index = len(self.requests) - 1
        output = self.outputs[min(index, len(self.outputs) - 1)]
        if output is None:
            return SliceResult(
                False, 7, ("fake",), (), None, (), "", "sequence failed", 0.01,
                failure_reason="synthetic later slicer failure",
            )
        request.output_directory.mkdir(parents=True, exist_ok=True)
        path = request.output_directory / "tower.gcode"
        path.write_text(output, encoding="utf-8")
        return SliceResult(
            True, 0, ("fake",), (path,), path, (), "ok", "", 0.01
        )


class TransientAnycubicCompatibilityAdapter(FakeAdapter):
    adapter_id = "anycubic_slicer_next"

    def __init__(self, gcode: str) -> None:
        super().__init__(gcode)
        self.attempt_count = 0

    def slice_model(self, request):
        self.attempt_count += 1
        if self.attempt_count == 1:
            return SliceResult(
                False,
                -17,
                ("fake-anycubic",),
                (),
                None,
                (),
                "process not compatible with printer",
                "",
                0.01,
                failure_reason="Der Slicer wurde mit Fehlercode -17 beendet.",
            )
        return super().slice_model(request)


