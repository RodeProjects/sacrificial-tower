    def test_01_config_rejects_unbounded_values(self) -> None:
        self.assertEqual(CalibrationConfig().maximum_iterations, 5)
        self.assertEqual(CalibrationConfig(maximum_iterations=0).maximum_iterations, 0)
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_iterations=-1)
        self.assertEqual(CalibrationConfig(maximum_iterations=10).maximum_iterations, 10)
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_iterations=11)
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_runtime_s=float("inf"))
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_path_growth_factor=0.5)

    def test_02_temporary_profile_neutralizes_slowdown_without_source_write(self) -> None:
        before = {
            path: path.read_bytes()
            for path in (self.machine, self.process, self.filament)
        }
        calibrated, overrides = build_calibration_profile(self.profile, self.root / "temp_profile")
        self.assertEqual(overrides["slow_down_layer_time"], "0")
        self.assertEqual(overrides["slow_down_for_layer_cooling"], "0")
        self.assertEqual(
            {path: path.read_bytes() for path in before},
            before,
        )
        source_paths = set(before)
        temporary_records = (
            calibrated.machine,
            calibrated.process,
            *calibrated.filaments,
        )
        for record in temporary_records:
            self.assertNotIn(record.path, source_paths)
            self.assertTrue(record.metadata["temporary"])
            self.assertEqual(record.source, "temporary")
            payload = json.loads(record.path.read_text(encoding="utf-8"))
            self.assertEqual(payload["type"], record.kind.value)
            self.assertEqual(payload["from"], "system")
        for record in (calibrated.process, *calibrated.filaments):
            payload = json.loads(record.path.read_text(encoding="utf-8"))
            self.assertEqual(payload["slow_down_layer_time"], "0")
            self.assertEqual(payload["slow_down_for_layer_cooling"], "0")

