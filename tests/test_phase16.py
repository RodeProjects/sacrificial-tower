    def test_01_config_rejects_unbounded_values(self) -> None:
        self.assertEqual(CalibrationConfig().maximum_iterations, 5)
        with self.assertRaisesRegex(ValueError, "mindestens einen Slicer-Durchlauf"):
            CalibrationConfig(maximum_iterations=0)
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_iterations=-1)
        self.assertEqual(CalibrationConfig(maximum_iterations=31).maximum_iterations, 31)
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_iterations=32)
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_iterations=31, maximum_joint_slices=26)
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_joint_slices=6, minimum_joint_slices=7)
        self.assertEqual(
            CalibrationConfig(
                maximum_joint_slices=1,
                minimum_joint_slices=5,
                completed_joint_slices_before_run=5,
            ).completed_joint_slices_before_run,
            5,
        )
        with self.assertRaises(ValueError):
            CalibrationConfig(completed_joint_slices_before_run=-1)
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_runtime_s=float("inf"))
        with self.assertRaises(ValueError):
            CalibrationConfig(maximum_path_growth_factor=0.5)

