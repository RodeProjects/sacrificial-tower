def sliced_layers(z_values=(.2, .4, .8), heights=(.2, .2, .2), roles=None):
    lines = ["G90", "M83"]
    previous = 0
    for index, (z, height) in enumerate(zip(z_values, heights)):
        lines.extend((";LAYER_CHANGE", f";Z:{z}", f";HEIGHT:{z - previous}",
                      f"G1 Z{z} F600", ";TYPE:" + (roles[index] if roles else "External perimeter"),
                      f";HEIGHT:{height}", f"G1 X{10 + index} Y10 E0.4 F900"))
        previous = z
    return "\n".join(lines) + "\n"


class EmptyLayerTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.path = Path(temporary.name) / "slice.gcode"

    def inspect(self, text):
        self.path.write_text(text, encoding="utf-8")
        snapshot = GCodeAnalysisService().analyze(self.path)
        return inspect_empty_layers(snapshot)

    def test_missing_planes_are_detected_without_a_slicer_warning(self):
        evidence = self.inspect(sliced_layers())
        self.assertTrue(evidence.detected)
        self.assertFalse(evidence.reported_by_slicer)
        self.assertEqual(len(evidence.gaps_mm), 1)
        self.assertAlmostEqual(evidence.gaps_mm[0][0], .4)
        self.assertAlmostEqual(evidence.gaps_mm[0][1], .6)

    def test_adaptive_heights_and_z_hops_are_not_empty_layers(self):
        text = sliced_layers((.2, .5, .65), (.2, .3, .15))
        text = text.replace(";LAYER_CHANGE\n;Z:0.5", "G1 Z5 F600\nG1 Z0.2 F600\n;LAYER_CHANGE\n;Z:0.5")
        self.assertFalse(self.inspect(text).detected)

    def test_intentional_support_contact_gaps_are_not_diagnosed(self):
        for roles in (("External perimeter", "Support material", "External perimeter"),
                      ("External perimeter", "External perimeter", "Support material interface")):
            with self.subTest(roles=roles):
                self.assertFalse(self.inspect(sliced_layers(roles=roles)).detected)

    def test_missing_or_invalid_height_tags_do_not_guess_from_z_steps(self):
        for value in ("nan", "inf", "invalid", "0", "-0.2"):
            with self.subTest(value=value):
                self.assertFalse(self.inspect(sliced_layers().replace(";HEIGHT:", ";IGNORED:")
                    .replace(";TYPE:External perimeter", f";TYPE:External perimeter\n;HEIGHT:{value}")).detected)

    def test_bambu_markers_and_an_explicit_empty_middle_layer(self):
        text = "; generated by BambuStudio 2.4.0\n" + sliced_layers((.2, .4, .6))
        text = text.replace(";LAYER_CHANGE", "; CHANGE_LAYER").replace(";Z:", "; Z_HEIGHT:")
        text = text.replace(";HEIGHT:", "; LAYER_HEIGHT:")
        text = text.replace("G1 X11 Y10 E0.4 F900", "G1 X11 Y10 F900")
        self.assertTrue(self.inspect(text).detected)

    def test_reports_distinguish_warnings_from_normal_cleanup_logs(self):
        for output in ("Warning: Empty layers detected, the output would not be printable.",
                       "Error: Empty initial layer", "Leere Schichten erkannt"):
            self.assertTrue(reports_empty_layers(output))
        for output in ("Slicing objects - removing top empty layers", "No empty layers detected"):
            self.assertFalse(reports_empty_layers(output))

    def test_message_only_recommends_an_available_simulation(self):
        evidence = EmptyLayerEvidence(True)
        enabled = empty_layer_message(evidence, simulation_available=True)
        self.assertIn("Stützen für STL-Objekt simulieren", enabled)
        self.assertIn("Originalobjekt", enabled)
        direct = empty_layer_message(evidence, simulation_available=True, direct_simulation_action=True)
        self.assertIn("Stützen simulieren", direct)
        self.assertIn("iterativen und manuellen Turmerstellung", direct)
        for active in (False, True):
            message = empty_layer_message(evidence, simulation_available=False, supports_active=active)
            self.assertNotIn("simulieren", message)
            self.assertEqual("bereits aktiviert" in message, active)

    def test_scan_is_cancelable(self):
        self.path.write_text(sliced_layers(), encoding="utf-8")
        snapshot = GCodeAnalysisService().analyze(self.path)
        def cancel():
            raise SourcePreSliceCancelled("cancel")
        with self.assertRaises(SourcePreSliceCancelled):
            inspect_empty_layers(snapshot, check_cancel=cancel)


class _Adapter(fixtures.FakeSliceAdapter):
    output = ""
    text = sliced_layers()

    def slice_model(self, request):
        result = super().slice_model(request)
        result.gcode_path.write_text(self.text, encoding="utf-8")
        return replace(result, stderr=self.output)


class EmptyLayerPresliceTests(unittest.TestCase):
    def setUp(self):
        self.f = fixtures.SourcePreSliceServiceTests()
        self.f.setUp()
        self.addCleanup(self.f.tearDown)
        self.f.service.cache = PreSliceCache(self.f.app_root / "cache")

    def run_slice(self, adapter):
        result = self.f.service.run(stl_validation=self.f.validation, profile_match=self.f.match,
                                  confirmation=self.f.confirmation, adapter=adapter)
        self.addCleanup(result.cleanup)
        return result

    def test_fresh_and_cached_preslices_retain_geometric_warning_and_original_files(self):
        originals = {path: path.read_bytes() for path in (self.f.source, *self.f.match.selected.source_paths)}
        adapter = _Adapter()
        fresh = self.run_slice(adapter)
        cached = self.run_slice(adapter)
        self.assertFalse(fresh.cache_hit)
        self.assertTrue(cached.cache_hit)
        self.assertTrue(fresh.empty_layers.detected)
        self.assertEqual(fresh.empty_layers, cached.empty_layers)
        self.assertEqual(len(adapter.requests), 1)
        self.assertEqual(originals, {path: path.read_bytes() for path in originals})

    def test_successful_cli_only_warnings_are_not_lost_by_caching(self):
        adapter = _Adapter()
        adapter.text = sliced_layers((.2, .4, .6))
        adapter.output = "Slicing warning: Empty layers detected, the output would not be printable."
        for _ in range(2):
            result = self.run_slice(adapter)
            self.assertTrue(result.empty_layers.reported_by_slicer)
            self.assertFalse(result.cache_hit)
        self.assertEqual(len(adapter.requests), 2)

    def test_failed_slice_explains_reported_empty_layers(self):
        class FailedAdapter(_Adapter):
            def slice_model(self, request):
                return replace(super().slice_model(request), success=False, return_code=1,
                               stderr="Empty layers detected, the output would not be printable.")
        with self.assertRaisesRegex(SourcePreSliceError, "leere Schichten") as caught:
            self.run_slice(FailedAdapter())
        self.assertNotIn("simulieren", str(caught.exception))


if __name__ == "__main__":
    unittest.main()
