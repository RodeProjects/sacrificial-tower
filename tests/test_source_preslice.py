def printable_gcode(
    *,
    conflicting_slicer: bool = False,
    printer_settings_id: str | None = None,
) -> str:
    prefix = (
        "; generated by PrusaSlicer 2.9.0\n"
        if conflicting_slicer
        else "; source pre-slice test\n"
    )
    if printer_settings_id is not None:
        prefix += f"; printer_settings_id = {printer_settings_id}\n"
    return prefix + "\n".join(
        (
            "G90",
            "M83",
            "G1 Z0.20 F600",
            "G1 X10 Y10 E0.4 F900",
            "G1 X11 Y11 E0.4 F900",
            "G1 Z0.40 F600",
            "G1 X12 Y10 E0.4 F900",
            "G1 X13 Y11 E0.4 F900",
            "",
        )
    )


class FakeSliceAdapter:
    adapter_id = "test-full"

    def __init__(self, mode: str = "success") -> None:
        self.mode = mode
        self.requests = []
        self.outside_path: Path | None = None

    def slice_model(self, request):
        self.requests.append(request)
        if self.mode == "cancel":
            assert request.cancellation_event is not None
            request.cancellation_event.set()
            return self._result(request, None, cancelled=True)
        if self.mode == "failure":
            return self._result(
                request,
                None,
                success=False,
                failure_reason="Kontrollierter Slicerfehler",
            )
        if self.mode == "outside":
            self.outside_path = request.output_directory.parent.parent / "outside.gcode"
            self.outside_path.write_text(printable_gcode(), encoding="utf-8")
            return self._result(request, self.outside_path)
        path = request.output_directory / "internal_analysis.gcode"
        path.write_text(
            printable_gcode(
                conflicting_slicer=self.mode == "metadata_mismatch",
                printer_settings_id=(
                    request.profile.machine.name
                    if self.mode == "generated_profile_metadata"
                    else None
                ),
            ),
            encoding="utf-8",
        )
        return self._result(request, path)

    @staticmethod
    def _result(
        request,
        path: Path | None,
        *,
        success: bool = True,
        cancelled: bool = False,
        failure_reason: str | None = None,
    ) -> SliceResult:
        return SliceResult(
            success=success,
            return_code=0 if success else 2,
            command=("test-slicer",),
            output_files=(path,) if path is not None else (),
            gcode_path=path,
            metadata_paths=(),
            stdout="",
            stderr="",
            duration_s=0.01,
            failure_reason=failure_reason,
            cancelled=cancelled,
        )


