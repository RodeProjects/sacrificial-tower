        source_hash = self._digest(self.source)
        profile_hashes = {
            record.path: self._digest(record.path)
            for record in (self.machine, self.process, self.filament)
        }
        phases = []
        adapter = FakeSliceAdapter()
        result = self.service.run(
            stl_validation=self.validation,
            profile_match=self.match,
            confirmation=self.confirmation,
            adapter=adapter,
            progress_callback=lambda percent, status, busy: phases.append(
                (percent, status, busy)
            ),
        )
        try:
            self.assertEqual(result.analysis_snapshot.layer_count, 2)
            self.assertTrue(result.metadata_verified)
            self.assertTrue(result.workspace_root.is_dir())
            self.assertTrue(
                result.prepared_source.analysis_gcode_path.is_relative_to(
                    result.workspace_root
                )
            )
            self.assertEqual(
                result.prepared_source.preslice_provenance.cache_key,
                build_preslice_cache_key(
                    stl_validation=self.validation,
                    profile_match=self.match,
                    confirmation=self.confirmation,
                ),
            )
            request = adapter.requests[0]
            self.assertEqual(request.purpose, "source_preslice")
            self.assertEqual(
                request.temporary_overrides,
                {
                    "slow_down_for_layer_cooling": False,
                    "slow_down_layer_time": 0,
                },
            )
            self.assertEqual(
                request.profile.effective_values["slow_down_for_layer_cooling"],
                False,
            )
            self.assertEqual(
                request.profile.effective_values["slow_down_layer_time"],
                0,
            )
            self.assertEqual(request.timeout_s, 17)
            self.assertEqual(
                request.model_path,
                self.validation.source_artifact.original_path,
            )
            self.assertTrue(request.model_path.samefile(self.source))
            self.assertTrue(request.output_directory.is_relative_to(result.workspace_root))
            self.assertTrue(any(busy for _, _, busy in phases))
            analysis_phases = [
                (percent, status, busy)
                for percent, status, busy in phases
                if 70 <= percent < 90 and "%" in status
            ]
            self.assertGreaterEqual(len(analysis_phases), 3)
            self.assertTrue(all(not busy for _, _, busy in analysis_phases))
            self.assertTrue(
                any("100 %" in status for _, status, _ in analysis_phases)
            )
            self.assertEqual(phases[-1][0], 100)
            self.assertEqual(self._digest(self.source), source_hash)
            for path, digest in profile_hashes.items():
                self.assertEqual(self._digest(path), digest)
        finally:
            workspace = result.workspace_root
            result.cleanup()
            self.assertFalse(workspace.exists())

