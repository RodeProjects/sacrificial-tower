class PreviewSeamTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.app = QApplication.instance() or QApplication([])

    def test_full_path_seams_match_native_and_python_before_sampling(self):
        expected = (Point3D(10,10,.2), Point3D(10,10,.4))
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory)/"seams.gcode"
            source.write_text(SOURCE)
            for python in ("0", "1"):
                with self.subTest(python=python), patch.dict(os.environ, {"COOLING_TOWER_FORCE_PYTHON_ANALYSIS":python}):
                    collector = DepositionToolpathCollector(maximum_segments=100)
                    try:
                        GCodeAnalysisService().analyze(source, event_observers=(collector.consume,))
                        result = collector.finish(expected_layer_count=2)
                        self.assertEqual(result.seam_points, expected)
                    finally:
                        collector.close()
            self.assertEqual(source.read_text(), SOURCE)

    def test_seam_markers_render_light_grey_and_follow_layer_selection(self):
        canvas = PreviewCanvas()
        try:
            canvas.resize(640,480)
            canvas.set_layer_context_enabled(True)
            canvas.set_scene(PreviewScene(
                (LineSegment3D(Point3D(10,10,.2), Point3D(40,10,.2)),), (),
                BedBounds(0,50,0,50), (0,0), 1, 1, 0,
                seam_points=(Point3D(15,10,.2),Point3D(35,10,.4))))
            frame = canvas._prepare_line_frame()
            self.assertEqual(sum(map(len,frame.seam_blocks)),2)
            image = QImage(640,480,QImage.Format.Format_RGB32)
            painter = QPainter(image)
            canvas.render(painter,QPoint())
            painter.end()
            self.assertTrue(any(image.pixelColor(x,y)==QColor(PreviewCanvas.SEAM_COLOR)
                for x in range(image.width()) for y in range(image.height())))
            canvas.set_layer_height(.2)
            self.assertEqual(sum(map(len,canvas._prepare_line_frame().seam_blocks)),1)
        finally:
            dispose_test_widget(canvas)

    def test_postprocessor_preview_keeps_seams_from_generated_gcode(self):
        from test_preprocessor import PreprocessorTests, make_gcode

        fixture = PreprocessorTests()
        fixture.setUp()
        self.addCleanup(fixture.tearDown)
        request = fixture.request(make_gcode().replace(";HEIGHT:0.2", ";HEIGHT:0.2\n;TYPE:External perimeter"))
        original = request.prepared_source.analysis_gcode_path.read_bytes()
        result = fixture.prepare(request)
        self.assertTrue(result.scene.seam_points)
        canvas = PreviewCanvas()
        self.addCleanup(dispose_test_widget, canvas)
        canvas.resize(640, 480)
        canvas.set_scene(result.scene)
        self.assertGreater(sum(map(len, canvas._prepare_line_frame().seam_blocks)), 0)
        self.assertEqual(request.prepared_source.analysis_gcode_path.read_bytes(), original)

    def test_iterative_preview_omits_source_seams_and_legend_entry(self):
        from cooling_tower.gui.preview_dialog import PreviewDialog
        from cooling_tower.preview import PreviewService
        from PySide6.QtWidgets import QLabel
        from test_preview_source_cache import PreviewSourceCacheIntegrationTests, SyntheticSuccessfulCalibrator

        fixture = PreviewSourceCacheIntegrationTests()
        fixture.setUp()
        self.addCleanup(fixture.tearDown)
        fixture.source.write_text(SOURCE, encoding="utf-8")
        fixture.snapshot = GCodeAnalysisService().analyze(fixture.source)
        service = PreviewService(SyntheticSuccessfulCalibrator())
        request = fixture.request()
        data = service._source_data(request, cancellation_event=None, notify=lambda *_: None)
        self.assertTrue(data.seam_points)
        result = service.prepare(request)
        self.addCleanup(result.dispose)
        self.assertEqual(result.scene.seam_points, ())
        dialog = PreviewDialog()
        self.addCleanup(dispose_test_widget, dialog)
        dialog.set_preview(result)
        self.assertEqual(dialog.canvas._prepare_line_frame().seam_blocks, ())
        self.assertNotIn("Seams", [label.text() for label in dialog.legend_widget.findChildren(QLabel)])

    def test_restarted_wall_paths_are_marked_for_each_slicer_family(self):
        text = SOURCE.replace(";TYPE:Internal solid infill", ";TYPE:Outer wall\nG1 X35 E.2\n;TYPE:Internal solid infill")
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory)/"seams.gcode"
            for producer in ("AnycubicSlicerNext", "OrcaSlicer", "BambuStudio", "PrusaSlicer"):
                variant = text.replace("AnycubicSlicerNext",producer)
                if producer == "BambuStudio":
                    variant=variant.replace(";LAYER_CHANGE","; CHANGE_LAYER").replace(";Z:","; Z_HEIGHT:").replace(";HEIGHT:","; LAYER_HEIGHT:")
                source.write_text(variant)
                for python in ("0","1"):
                    with self.subTest(producer=producer,python=python), patch.dict(os.environ,{"COOLING_TOWER_FORCE_PYTHON_ANALYSIS":python}):
                        collector=DepositionToolpathCollector()
                        try:
                            GCodeAnalysisService().analyze(source,event_observers=(collector.consume,))
                            self.assertEqual(collector.finish(expected_layer_count=2).seam_points,
                                (Point3D(10,10,.2),Point3D(30,30,.2),Point3D(10,10,.4)))
                        finally:
                            collector.close()

    def test_marker_storage_stays_bounded_and_keeps_late_layers(self):
        from cooling_tower.gcode.parser import MachineStateTracker, GCodeLine, parse_gcode_line
        collector = SeamCollector()
        collector.MAXIMUM_POINTS=8
        tracker = MachineStateTracker()
        for number, text in enumerate(["M83","G1 F600"]+[
                line for i in range(40) for line in (";TYPE:Outer wall",f"G1 Z{i+.2}",f"G1 X{10+i%2} E.1")],1):
            parsed = parse_gcode_line(GCodeLine(number,text))
            collector.consume(parsed,tracker.process_line(parsed))
        self.assertLessEqual(len(collector.points),8)
        self.assertGreater(collector.points[-1].z,20)

    def test_only_outer_wall_starts_are_marked_in_native_and_python(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory)/"walls.gcode"
            for producer in ("AnycubicSlicerNext", "OrcaSlicer", "BambuStudio", "PrusaSlicer"):
                for outer in ("Outer wall", "External perimeter"):
                    text=SOURCE.replace("AnycubicSlicerNext",producer).replace("Outer wall",outer)
                    hidden = "\n".join(f";TYPE:{feature}\nG1 X{40+i} Y30\nG1 X{42+i} E.2"
                        for i,feature in enumerate(("Inner wall","Perimeter","Overhang wall","Overhang perimeter")))
                    text=text.replace(";TYPE:Internal solid infill",hidden+"\n;TYPE:Internal solid infill")
                    source.write_text(text)
                    for python in ("0","1"):
                        with self.subTest(producer=producer,outer=outer,python=python), patch.dict(os.environ,{"COOLING_TOWER_FORCE_PYTHON_ANALYSIS":python}):
                            collector=DepositionToolpathCollector()
                            try:
                                service=GCodeAnalysisService()
                                service.analyze(source,event_observers=(collector.consume,))
                                self.assertEqual(collector.finish(expected_layer_count=2).seam_points,
                                    (Point3D(10,10,.2),Point3D(10,10,.4)))
                                if python=="0":
                                    self.assertTrue(service.native_full_analysis_info["used"])
                            finally:
                                collector.close()

    def test_seam_swatch_has_light_fill_and_visible_grey_border(self):
        from cooling_tower.gui.widgets.manual_preview_info import LegendSwatch
        from cooling_tower.gui.design_tokens import PREVIEW_SEAM_BORDER_COLOR
        swatch = LegendSwatch(PreviewCanvas.SEAM_COLOR)
        try:
            image = swatch.grab().toImage()
            self.assertEqual(image.pixelColor(image.width()//2,image.height()//2),QColor("#e9e9e9"))
            self.assertEqual(image.pixelColor(0,0),QColor(PREVIEW_SEAM_BORDER_COLOR))
        finally:
            dispose_test_widget(swatch)


