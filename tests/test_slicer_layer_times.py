from __future__ import annotations

import json
import sys
import tempfile
import unittest
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from cooling_tower.calibration.slice_evaluator import SliceEvaluator
from cooling_tower.gcode.slicer_layer_times import (
    anycubic_timing_hooks,
    read_slicer_layer_times,
)
from cooling_tower.services.analysis_service import GCodeAnalysisService
from cooling_tower.slicers import (
    EffectiveProfile, ProfileKind, ProfileRecord, SliceRequest, SliceResult,
    SlicerDiscoverySource, SlicerInstallation,
)
from cooling_tower.slicers.adapters import AnycubicSlicerNextAdapter, FULL_CAPABILITIES


def native_gcode() -> str:
    return """; generated by AnycubicSlicerNext 2.0.0.3
G90
M83
M204 S1000
; COOLING_TOWER_NATIVE_LAYER 0 Z 0.2
;_GP_INLINE_ESTIMATED_PRINTING_TIME_PLACEHOLDER
G1 Z0.2 F600
G1 X10 Y10 E1 F600
; COOLING_TOWER_NATIVE_LAYER 1 Z 0.4
; estimated printing time (normal mode) = 1m 40s = 100.000
G1 Z0.4 F600
G1 X20 Y10 E1 F600
; COOLING_TOWER_NATIVE_LAYER 2 Z 0.6
; estimated printing time (normal mode) = 1m 53s = 113.760
G1 Z0.6 F600
G1 X30 Y10 E1 F600
; COOLING_TOWER_NATIVE_END
; estimated printing time (normal mode) = 2m 7s = 127.780
G1 X200 F600
"""


class SlicerLayerTimesTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.source = self.root / "native.gcode"
        self.source.write_text(native_gcode(), encoding="utf-8")

    def test_native_clocks_supply_all_layers_and_exclude_shutdown(self) -> None:
        times = read_slicer_layer_times(self.source)
        self.assertIsNotNone(times)
        self.assertEqual(times.z_values_mm, (0.2, 0.4, 0.6))
        for actual, expected in zip(times.times_s, (100.0, 13.76, 14.02)):
            self.assertAlmostEqual(actual, expected)

    def test_native_totals_drive_snapshot_and_evaluator(self) -> None:
        snapshot = GCodeAnalysisService().analyze(self.source, force=True)
        self.assertAlmostEqual(snapshot.minimum_layer_time_s, 13.76)
        self.assertAlmostEqual(snapshot.layers[1].total_time_s, 13.76)
        self.assertLess(snapshot.layers[1].deposition_time_s, 2)
        result = SliceResult(True, 0, (), (self.source,), self.source, (), "", "", 0)
        evaluation = SliceEvaluator().evaluate(result, snapshot.layers)
        self.assertEqual(evaluation.metadata_source, "slicer_native_gcode")
        self.assertAlmostEqual(evaluation.minimum_sliced_layer_time_s, 13.76)
        self.assertAlmostEqual(evaluation.layer_timings[1].total_added_time_s, 13.76)
        self.assertAlmostEqual(evaluation.layer_timings[1].slicer_reported_time_s, 13.76)

    def test_startup_clock_is_subtracted_when_available(self) -> None:
        text = native_gcode().replace(
            ";_GP_INLINE_ESTIMATED_PRINTING_TIME_PLACEHOLDER",
            "; estimated printing time (normal mode) = 5s = 5.000",
        )
        self.source.write_text(text, encoding="utf-8")
        self.assertAlmostEqual(read_slicer_layer_times(self.source).times_s[0], 95)

    def test_unannotated_gcode_retains_established_analysis(self) -> None:
        self.source.write_text("G90\nM83\nG1 Z0.2 F600\nG1 X10 E1 F600\n", encoding="utf-8")
        self.assertIsNone(read_slicer_layer_times(self.source))
        self.assertLess(GCodeAnalysisService().analyze(self.source).minimum_layer_time_s, 2)

    def test_incomplete_duplicate_and_reversed_clocks_are_rejected(self) -> None:
        for text in (
            native_gcode().replace(" = 113.760", ""),
            native_gcode().replace("LAYER 2 Z", "LAYER 1 Z"),
            native_gcode().replace(" = 127.780", " = 110.000"),
            native_gcode().replace("; COOLING_TOWER_NATIVE_END", "; missing end"),
        ):
            with self.subTest(text=text):
                self.source.write_text(text, encoding="utf-8")
                with self.assertRaises(ValueError):
                    read_slicer_layer_times(self.source)

    def test_clock_layer_heights_must_match_the_actual_gcode(self) -> None:
        self.source.write_text(native_gcode().replace("LAYER 2 Z 0.6", "LAYER 2 Z 0.8"), encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "G-Code-Layern"):
            GCodeAnalysisService().analyze(self.source)

    def test_integration_invalidates_native_clocks_of_the_inputs(self) -> None:
        self.source.write_text(native_gcode().replace("G1 X20", "; --- COOLING_TOWER_BEGIN\nG1 X20"), encoding="utf-8")
        self.assertIsNone(read_slicer_layer_times(self.source))

    def test_hooks_preserve_custom_instructions_and_are_idempotent(self) -> None:
        values = {"before_layer_change_gcode": "M117 Layer [layer_num]", "machine_end_gcode": "M104 S0"}
        hooks = anycubic_timing_hooks(values)
        self.assertTrue(hooks["before_layer_change_gcode"].startswith(values["before_layer_change_gcode"]))
        self.assertTrue(hooks["machine_end_gcode"].endswith(values["machine_end_gcode"]))
        self.assertEqual(anycubic_timing_hooks(hooks), hooks)

    def test_adapter_only_changes_its_own_machine_copy(self) -> None:
        executable = self.root / "AnycubicSlicerNext.exe"
        executable.write_bytes(b"fixture")
        installation = SlicerInstallation(
            "anycubic_slicer_next", "Anycubic Slicer Next", "2.0.0.3", executable,
            True, FULL_CAPABILITIES, SlicerDiscoverySource.KNOWN_PATH,
        )
        records = []
        for kind in (ProfileKind.MACHINE, ProfileKind.PROCESS):
            path = self.root / (kind.value + ".json")
            path.write_text(json.dumps({"type": kind.value, "name": kind.value}), encoding="utf-8")
            records.append(ProfileRecord("anycubic_slicer_next", kind.value, kind.value, kind, path, "user"))
        originals = {r.path: r.path.read_bytes() for r in records}
        model = self.root / "input.stl"
        model.write_bytes(b"fixture")
        profile = EffectiveProfile(installation, *records, (), effective_values={"machine_end_gcode": "M104 S0"})
        request = SliceRequest(model, profile, self.root / "output")
        _, arguments = AnycubicSlicerNextAdapter().build_slice_command(request, model, request.output_directory, self.root / "work")
        copies = arguments[arguments.index("--load-settings") + 1].split(";")
        machine = json.loads(Path(copies[0]).read_text(encoding="utf-8"))
        self.assertIn("COOLING_TOWER_NATIVE_LAYER", machine["before_layer_change_gcode"])
        self.assertTrue(machine["machine_end_gcode"].endswith("M104 S0"))
        self.assertEqual(originals, {r.path: r.path.read_bytes() for r in records})


if __name__ == "__main__":
    unittest.main()
