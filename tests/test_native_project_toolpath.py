from pathlib import Path
from contextlib import nullcontext
import sys
import tempfile
import unittest
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))
import cooling_tower.gcode.native_analysis as native_module
from cooling_tower.native_project.toolpath import DepositionToolpathCollector
from cooling_tower.services.analysis_service import GCodeAnalysisService
from cooling_tower.preview.toolpath import DepositionToolpathCollector as StlCollector


class NativeToolpathBoundsTests(unittest.TestCase):
    def test_route_sampling_is_bounded_and_matches_python(self):
        results=[]
        with tempfile.TemporaryDirectory() as temporary:
            path=Path(temporary)/'many-routes.gcode'
            path.write_text('; generated by OrcaSlicer 2.4.2\nG90\nM83\n'
                '; CHANGE_LAYER\n; Z_HEIGHT: 0.2\n; LAYER_HEIGHT: 0.2\nG1 Z0.2 F600\nG1 X1 E1\n'
                +'\n'.join(f'G1 X{x} Y{x%2}' for x in range(2,1003))+'\nG1 X1003 E1\n',encoding='utf-8')
            for fallback in (False,True):
                collector=DepositionToolpathCollector(maximum_segments=100)
                try:
                    with patch.object(native_module,'_native_timing',None) if fallback else nullcontext():
                        analysis=GCodeAnalysisService().analyze(path,event_observers=(collector.consume,))
                    result=collector.finish(expected_layer_count=analysis.layer_count,layer_records=analysis.layers)
                    self.assertEqual(len(result.travel_segments),100)
                    self.assertEqual(set(result.travel_layer_z),{.2})
                    results.append(result.travel_segments)
                finally:collector.close()
        self.assertEqual(*results)

    def test_travel_preview_keeps_hops_on_the_print_layer_without_changing_bounds(self):
        results=[]
        for fallback in (False,True):
            with self.subTest(fallback=fallback),tempfile.TemporaryDirectory() as temporary:
                path=Path(temporary)/'routes.gcode'
                path.write_text('; generated by OrcaSlicer 2.4.2\nG90\nM83\n'
                    'G1 X500 Y500 Z1 F600\n; CHANGE_LAYER\n; Z_HEIGHT: 0.2\n; LAYER_HEIGHT: 0.2\n'
                    'G1 X0 Y0 Z0.3 F600\nG1 X1 E1\nG1 Z0.8\nG1 X2 Y2\nG1 Z0.3\nG1 X3 E1\n'
                    '; CHANGE_LAYER\n; Z_HEIGHT: 0.4\n; LAYER_HEIGHT: 0.2\n'
                    'G1 Z0.5\nG1 X5 E1\nG1 X6 Y3\n',encoding='utf-8')
                collector=DepositionToolpathCollector()
                try:
                    with patch.object(native_module,'_native_timing',None) if fallback else nullcontext():
                        analysis=GCodeAnalysisService().analyze(path,event_observers=(collector.consume,))
                    result=collector.finish(expected_layer_count=analysis.layer_count,layer_records=analysis.layers)
                    self.assertEqual(len(result.travel_segments),6)
                    self.assertEqual(result.travel_layer_z,(.2,.2,.2,.2,.4,.4))
                    self.assertEqual(result.travel_segments[1].end.z,.8)
                    self.assertEqual(result.occupied_bounds.maximum_x_mm,5.)
                    self.assertEqual(result.source_segment_count,3)
                    results.append((result.travel_segments,result.travel_layer_z))
                finally:collector.close()
        self.assertEqual(*results)

    def test_logical_layer_ownership_keeps_physical_z_offset_and_seams(self):
        for fallback in (False, True):
            with self.subTest(fallback=fallback), tempfile.TemporaryDirectory() as temporary:
                path = Path(temporary) / 'offset.gcode'
                path.write_text('; generated by OrcaSlicer 2.4.2\nG90\nM83\n'
                    '; CHANGE_LAYER\n; Z_HEIGHT: 0.2\n; LAYER_HEIGHT: 0.2\n'
                    '; TYPE:Outer wall\nG1 Z0.3 F600\nG1 X1 E1 F600\n'
                    '; CHANGE_LAYER\n; Z_HEIGHT: 0.4\n; LAYER_HEIGHT: 0.2\n'
                    '; TYPE:Outer wall\nG1 Z0.5\nG1 X2 E1 F600\n',encoding='utf-8')
                collector = DepositionToolpathCollector()
                try:
                    if fallback:
                        with patch.object(native_module, '_native_timing', None):
                            analysis = GCodeAnalysisService().analyze(path,event_observers=(collector.consume,))
                    else:
                        analysis = GCodeAnalysisService().analyze(path,event_observers=(collector.consume,))
                    result = collector.finish(expected_layer_count=analysis.layer_count)
                    self.assertEqual(result.segment_layer_z,(.2,.4))
                    self.assertEqual(tuple(segment.end.z for segment in result.object_segments),(.3,.5))
                    self.assertEqual(result.seam_layer_z,(.2,.4))
                    self.assertEqual(tuple(point.z for point in result.seam_points),(.3,.5))
                finally:
                    collector.close()

    def collect(self, arc, start, *, fallback=False, stl=False):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / 'neutral.gcode'
            path.write_text('\n'.join((
                '; generated by OrcaSlicer 2.4.2', 'G90', 'M83',
                'G1 Z0.3 F600', 'G1 X500 Y500 E1 F600',
                '; CHANGE_LAYER', '; Z_HEIGHT: 0.2', '; LAYER_HEIGHT: 0.2',
                'G1 Z0.2', start, arc,
            )), encoding='utf-8')
            collector = (StlCollector if stl else DepositionToolpathCollector)()
            try:
                service = GCodeAnalysisService()
                if fallback:
                    with patch.object(native_module, '_native_timing', None):
                        analysis = service.analyze(path, event_observers=(collector.consume,))
                else:
                    analysis = service.analyze(path, event_observers=(collector.consume,))
                return collector.finish(expected_layer_count=analysis.layer_count)
            finally:
                collector.close()

    def test_full_and_partial_arc_extrema_match_python_without_startup_purge(self):
        cases = (
            ('G3 X1 Y0 I1 J0 E1 F600', 'G1 X-1 Y0', (-1, 1, -1, 0)),
            ('G2 X1 Y0 I-1 J0 E1 F600', 'G1 X1 Y0', (-1, 1, -1, 1)),
            ('G3 X0 Y1 I-1 J0 E1 F600', 'G1 X1 Y0', (0, 1, 0, 1)),
            ('G2 X0 Y-1 R1 E1 F600', 'G1 X1 Y0', (0, 1, -1, 0)),
        )
        for arc, start, expected in cases:
            for fallback in (False, True):
                with self.subTest(arc=arc, fallback=fallback):
                    result = self.collect(arc, start, fallback=fallback)
                    bounds = result.occupied_bounds
                    self.assertIsNotNone(bounds)
                    actual = (bounds.minimum_x_mm, bounds.maximum_x_mm, bounds.minimum_y_mm, bounds.maximum_y_mm)
                    for a, e in zip(actual, expected):
                        self.assertAlmostEqual(a, e, places=6)
                    self.assertEqual(result.source_segment_count, 1)

    def test_native_preview_option_preserves_existing_stl_collector_behavior(self):
        result = self.collect('G1 X1 Y0 E1 F600', 'G1 X-1 Y0', stl=True)
        self.assertEqual(result.occupied_bounds.maximum_x_mm, 500)
        self.assertEqual(result.source_segment_count, 2)


if __name__ == '__main__':
    unittest.main()
