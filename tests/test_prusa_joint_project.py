class PrusaJointProjectTests(unittest.TestCase):
    def setUp(self):
        fixture = prusa_fixtures.PrusaSlicerIntegrationTests()
        fixture.setUp()
        self.addCleanup(fixture.doCleanups)
        self.fixture = fixture
        fixture._create_profile_fixtures()
        with patch.dict(os.environ, {"APPDATA": str(fixture.appdata)}):
            records = {r.name: r for r in fixture.adapter.discover_profiles(fixture.installation) if r.source == "user"}
        self.profile = EffectiveProfile(
            installation=fixture.installation,
            machine=records["MK4S HF0.4 - Eigenes Maschinenprofil"],
            process=records["Eigenes Prozessprofil"],
            filaments=(records["Eigenes Filament"],),
            effective_values={"layer_height": ".2", "fill_density": "15%",
                              "bed_shape": "0x0,250x0,250x210,0x210"},
        )
        self.root = fixture.root
        self.source = self.root / "source.stl"
        self.tower = self.root / "tower.stl"
        trimesh.creation.box((10, 10, 10)).export(self.source)
        trimesh.creation.box((6, 6, 10)).export(self.tower)
        self.request = SliceRequest(self.source, self.profile, self.root / "output")
        self.occupied = OccupiedBounds(120, 130, 100, 110)
        bed = parse_bed_geometry(self.profile.effective_values)
        self.placement = propose_tower_placement(bed.bounds, self.occupied, tower_radius_mm=5,
            object_clearance_mm=5, edge_clearance_mm=5, bed_geometry=bed)

        def complete_profile(executable, arguments, **options):
            self.assertTrue(Path(arguments[arguments.index("--load")+1]).is_file())
            self.assertIn(str(self.root), arguments[arguments.index("--datadir")+1])
            Path(arguments[arguments.index("--save")+1]).write_text(
                "# generated by PrusaSlicer\nlayer_height = .2\nfill_density = 15%\n"
                "gcode_label_objects = firmware\nbinary_gcode = 0\n", encoding="utf-8")
            return ProcessOutcome(tuple(arguments), 0, "", "", .01)
        fixture.adapter.runner.run.side_effect = complete_profile

    def build(self, path=None, **options):
        return build_prusa_joint_project(self.fixture.adapter, self.request, self.source, self.tower,
            path or self.root / "joint.3mf", occupied=self.occupied, placement=self.placement,
            tower_full_infill=True, **options)

    def test_native_opc_mesh_connectivity_placement_and_object_overrides(self):
        before = {p: p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        result = self.build(tower_supports_disabled=True, source_supports_enabled=True)
        self.assertEqual(validate_prusa_joint_project(result.path, tower_full_infill=True,
            tower_supports_disabled=True, source_supports_enabled=True), (1, 2))
        with zipfile.ZipFile(result.path) as archive:
            for path, tag in (("_rels/.rels", b"<Relationships"), ("[Content_Types].xml", b"<Types")):
                self.assertIn(tag, archive.read(path))
                self.assertNotIn(b"ns0:", archive.read(path))
            model = ET.fromstring(archive.read(MODEL_PATH))
            ns = {"m": MODEL_NAMESPACE}
            meshes = model.findall("m:resources/m:object/m:mesh", ns)
            self.assertEqual(len(meshes), 2)
            for mesh in meshes:
                self.assertEqual(len(mesh.findall("m:vertices/m:vertex", ns)), 8)
                self.assertEqual(len(mesh.findall("m:triangles/m:triangle", ns)), 12)
            items = model.findall("m:build/m:item", ns)
            offsets = [tuple(map(float, item.attrib["transform"].split()))[-3:] for item in items]
            self.assertEqual(offsets[0], (125., 105., 5.))
            self.assertEqual(offsets[1], (self.placement.center_x_mm, self.placement.center_y_mm, 5.))
            self.assertIn(b"; fill_density = 15%", archive.read(PRINT_CONFIG_PATH))
            metadata = ET.fromstring(archive.read(MODEL_CONFIG_PATH))
            roles = {o.attrib["id"]: {m.attrib["key"]:m.attrib["value"] for m in o.findall("metadata")}
                     for o in metadata.findall("object")}
            self.assertEqual(roles["2"]["fill_density"], "100%")
            self.assertNotIn("fill_density", roles["1"])
            self.assertEqual(roles['1']['support_material_auto'], '1')
            self.assertEqual(roles['1']['support_material_style'], 'organic')
            self.assertNotIn('support_material_style', roles['2'])
        with self.assertRaises(JointProjectError):
            validate_prusa_joint_project(result.path,tower_full_infill=True,source_supports_enabled=True,
                                         source_support_settings={'support_material_style':'grid'})
        for path, data in before.items():
            self.assertEqual(path.read_bytes(), data)

    def test_protected_slicer_directories_fail_before_execution(self):
        for root in (self.fixture.user_root, self.fixture.resource_profiles,
                     self.fixture.executable.parent):
            with self.subTest(root=root), self.assertRaises(ValueError):
                self.build(root / "forbidden.3mf")
        self.fixture.adapter.runner.run.assert_not_called()

    def test_failed_native_config_does_not_replace_destination(self):
        destination = self.root / "existing.3mf"
        destination.write_bytes(b"old artifact")
        self.fixture.adapter.runner.run.side_effect = lambda *args, **kw: ProcessOutcome((), None, "", "", 1., timed_out=True)
        with self.assertRaisesRegex(JointProjectError, "erlaubten Zeit"):
            self.build(destination)
        self.assertEqual(destination.read_bytes(), b"old artifact")

    def test_source_changed_during_native_config_does_not_replace_destination(self):
        destination = self.root / "existing.3mf"
        destination.write_bytes(b"old artifact")
        complete_profile = self.fixture.adapter.runner.run.side_effect
        def change_source(*args, **options):
            result = complete_profile(*args, **options)
            self.source.write_bytes(self.source.read_bytes() + b"changed")
            return result
        self.fixture.adapter.runner.run.side_effect = change_source
        with self.assertRaisesRegex(JointProjectError, "Quelldatei.*verändert"):
            self.build(destination)
        self.assertEqual(destination.read_bytes(), b"old artifact")

    def test_missing_project_metadata_is_rejected(self):
        path = self.root / "bad.3mf"
        with zipfile.ZipFile(path, "w") as archive:
            archive.writestr(MODEL_PATH, "<model/>")
        with self.assertRaisesRegex(JointProjectError, "unvollständig oder ungültig"):
            validate_prusa_joint_project(path, tower_full_infill=True)


class PrusaGCodeEvidenceTests(unittest.TestCase):
    def test_firmware_object_labels_are_restored_and_ended(self):
        labels = FirmwareObjectLabels()
        for text in ("M486 S0", "M486 Asource_object", "M486 S1", "M486 Acooling_tower", "M486 S-1"):
            labels.consume(parsed(text))
        self.assertIsNone(labels.active_name)
        labels.consume(parsed("M486 S1"))
        self.assertEqual(labels.active_name, "cooling_tower")
        labels.consume(parsed("M486 S.5"))
        self.assertIsNone(labels.active_name)
        labels.consume(parsed("M486 S1e30"))
        self.assertIsNone(labels.active_name)

    def test_dense_internal_infill_is_proven_and_sparse_is_rejected(self):
        for spacing in (.38, .45, 2.):
            collector = PrusaInfillEvidenceCollector()
            lines = ["G90", "M83", "M486 S1", "M486 Acooling_tower", "M486 S-1",
                     ";LAYER_CHANGE", "G1 Z.2 F600", "M486 S1", ";TYPE:Internal infill", ";WIDTH:.45"]
            for row in range(7):
                lines += [f"G0 X0 Y{row*spacing} F6000", f"G1 X10 Y{row*spacing} E.3 F1200"]
            for number, text in enumerate(lines):
                collector.consume(parsed(text, number))
            if spacing < 1.:
                collector.validate()
            else:
                with self.assertRaisesRegex(JointProjectError, "zu weit auseinander"):
                    collector.validate()

    def test_startup_purge_is_excluded_in_native_and_python_initial_and_joint_preview(self):
        text = "\n".join(("; generated by PrusaSlicer 2.9.6", "G90", "M83", "M486 S0",
            "M486 Asource_object", "G1 Z.2 F600", "G1 X40 Y-4 E1 F1200", ";LAYER_CHANGE",
            "G0 X120 Y100 F6000", "G1 X130 Y100 E.4 F1200", "M486 S1", "M486 Acooling_tower",
            "G0 X70 Y100 F6000", "G1 X75 Y100 E.3 F1200", "M486 S-1", "; gcode_flavor = marlin2"))
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "joint.gcode"
            path.write_text(text, encoding="utf-8")
            for force in ("0", "1"):
                with patch.dict(os.environ, {"COOLING_TOWER_FORCE_PYTHON_ANALYSIS": force}):
                    collector = DepositionToolpathCollector()
                    self.addCleanup(collector.close)
                    snapshot = GCodeAnalysisService().analyze(path, force=True, event_observers=(collector.consume,))
                    initial = collector.finish(expected_layer_count=snapshot.layer_count)
                    self.assertGreaterEqual(initial.occupied_bounds.minimum_x_mm, 70.)
                    self.assertEqual(initial.occupied_bounds.minimum_y_mm, 100.)
            joint = analyze_joint_source_toolpaths(path, tower_center_xy_mm=(72.5,100), expected_layer_count=1)
            self.assertEqual(joint.occupied_bounds.minimum_x_mm, 120.)
            self.assertEqual(joint.occupied_bounds.minimum_y_mm, 100.)
