    def _gcode(
        self,
        *,
        overrides: dict[str, object] | None = None,
        omit: tuple[str, ...] = (),
        body: tuple[str, ...] = (),
        slicer: str = "AnycubicSlicerNext 1.4.1.2",
    ):
        values: dict[str, object] = {
            "printer_settings_id": "Example M5 0.4 nozzle",
            "print_settings_id": "Quality 0.2",
            "filament_settings_id": '"Example PLA"',
            "printer_model": "Example M5",
            "printer_technology": "FFF",
            "nozzle_diameter": "0.4",
            "gcode_flavor": "klipper",
            "layer_height": "0.2",
            "line_width": "0.42",
            "outer_wall_speed": "50",
            "inner_wall_speed": "100",
            "travel_speed": "160",
            "default_acceleration": "5000",
            "wall_loops": "2",
            "min_print_speed": "15",
            "slow_down_layer_time": "10",
            "filament_max_volumetric_speed": "12",
            "fan_min_speed": "60",
            "fan_max_speed": "100",
            "retraction_speed": "60",
            "deretraction_speed": "60",
        }
        values.update(overrides or {})
        for key in omit:
            values.pop(key, None)
        comments = [
            f"; generated by {slicer}",
            "; CONFIG_BLOCK_START = begin",
            "; AnycubicSlicerNext_config = begin",
            *(f"; {key} = {value}" for key, value in values.items()),
            "; AnycubicSlicerNext_config = end",
            "; CONFIG_BLOCK_END = end",
        ]
        gcode = "\n".join(
            (
                *comments,
                "G90",
                "M83",
                *body,
                "G1 Z0.2 F600",
                "G1 X10 E1 F600",
                "G1 Z0.4 F600",
                "G1 Y10 E1 F600",
            )
        )
        path = self.root / f"source_{time.time_ns()}.gcode"
        path.write_text(gcode, encoding="utf-8")
        return GCodeAnalysisService().analyze(path, force=True)

    def service(self, *, validator=None, mapping=True, cache_path=None):
        return ProfileMatchingService(
            inventory_service=ProfileInventoryService(cache_path),
            mapping_store=(
                ProfileMappingStore(self.root / "profile_mappings.json")
                if mapping
                else None
            ),
            validator=validator or StructuralProfileValidator(),
        )

