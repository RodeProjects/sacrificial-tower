class SuccessfulProbeValidator:
    def validate(self, adapter, bundle, source_values, *, reconstructed):
        return ProfileValidationOutcome(
            ProfileValidationState.PROBE_VALIDATED,
            "synthetic probe passed",
        )


class FailingProbeValidator:
    def validate(self, adapter, bundle, source_values, *, reconstructed):
        return ProfileValidationOutcome(
            ProfileValidationState.INVALID,
            "synthetic probe rejected the profile",
        )


class ProbeRunner:
    def __init__(self) -> None:
        self.commands: list[tuple[str, ...]] = []
        self.loaded_profiles: list[dict[str, object]] = []

    def run(
        self,
        executable,
        arguments,
        *,
        working_directory,
        timeout_s,
        cancellation_event=None,
    ) -> ProcessOutcome:
        command = (str(executable), *(str(item) for item in arguments))
        self.commands.append(command)
        argument_list = list(arguments)
        settings_value = argument_list[
            argument_list.index("--load-settings") + 1
        ]
        filament_value = argument_list[
            argument_list.index("--load-filaments") + 1
        ]
        for path in (
            *(Path(value) for value in str(settings_value).split(";")),
            *(Path(value) for value in str(filament_value).split(";")),
        ):
            self.loaded_profiles.append(
                json.loads(path.read_text(encoding="utf-8"))
            )
        output_index = list(arguments).index("--outputdir")
        output = Path(arguments[output_index + 1])
        output.mkdir(parents=True, exist_ok=True)
        (output / "plate_1.gcode").write_text(
            "; generated by AnycubicSlicerNext 1.4.1.2\n"
            "G90\nM83\nG1 Z0.2 F600\nG1 X10 E1 F600\n"
            "G1 Z0.4 F600\nG1 Y10 E1 F600\n",
            encoding="utf-8",
        )
        return ProcessOutcome(
            command=command,
            return_code=0,
            stdout="probe ok",
            stderr="",
            duration_s=0.01,
        )


