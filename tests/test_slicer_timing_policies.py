def parsed(text, number=1):
    return parse_gcode_line(GCodeLine(number, text))


def timing_gcode(producer, flavor):
    lines = [
        f"; generated by {producer} 2.4.2", "M83", "G90", "M201 X1200 Y1600 Z100 E1000",
        "M203 X250 Y300 Z10 E30", "M204 P1200 T1500 R800", "M205 X8 Y9 Z.4 E3",
        "M205 J.01", "G1 Z.2 F600", ";LAYER_CHANGE",
    ]
    x = y = 0.
    for index in range(630):
        if index in {210, 420}:
            lines += [f"G1 Z{.2 + index / 1050:.4f} F600", ";LAYER_CHANGE"]
        if index == 300:
            lines += ["M205 J0 X6", "M204 P600"]
        if index == 350:
            lines += ["SET_VELOCITY_LIMIT ACCEL=900 SQUARE_CORNER_VELOCITY=4 VELOCITY=80"]
        if index == 440:
            lines += ["M205 J.02", "M204 P800"]
        if index % 37 == 0:
            lines += ["G2 X10 Y10 I5 J5 E.1 F2400", "G4 P10"]
            x = y = 10.
        x += (index % 7 - 2) * .21
        y += (index % 5 - 1) * .18
        lines += [f"G1 X{x:.4f} Y{y:.4f} E.05 F{1200 + index % 9 * 330}"]
    lines += [f"; gcode_flavor = {flavor}", "; machine_max_acceleration_extruding = 1000,800",
              "; machine_max_speed_x = 250,200", "; machine_max_feedrate_x = 250,200"]
    return "\r\n".join(lines) + "\r\n"


class SlicerTimingPolicyTests(unittest.TestCase):
    def test_policy_requires_exact_producer_and_explicit_dialect(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "timing.gcode"
            for producer, reader in (("OrcaSlicer", read_orca_timing_policy),
                                     ("PrusaSlicer", read_prusa_timing_policy)):
                for header in ("BambuStudio", "AnycubicSlicerNext", "SuperSlicer"):
                    path.write_text(timing_gcode(header, "marlin2"), encoding="utf-8")
                    self.assertIsNone(reader(path))
                path.write_text(f"; generated by {producer} 2.4.2\nG1 X1 F1000\n", encoding="utf-8")
                self.assertIsNone(reader(path))
                path.write_bytes((timing_gcode(producer, "marlin2") +
                    "; machine_max_jerk_x = nan\r\n; machine_max_jerk_y = -3\r\n").encode())
                policy = reader(path)
                self.assertTrue(policy.uses_junction_deviation)
                self.assertEqual(policy.limits["machine_max_acceleration_extruding"], 1000.)
                self.assertNotIn("machine_max_jerk_x", policy.limits)
                self.assertNotIn("machine_max_jerk_y", policy.limits)

    def test_orca_jd_restores_classic_jerk_and_caps_acceleration(self):
        tracker = OrcaMachineStateTracker(OrcaTimingPolicy("marlin2", {
            "machine_max_jerk_x": 8., "machine_max_jerk_y": 9.,
            "machine_max_acceleration_extruding": 1000., "machine_max_acceleration_x": 500.,
        }))
        tracker.process_line(parsed("M205 J.01"))
        self.assertAlmostEqual(tracker.state.jerk_x_mm_s, math.sqrt(12.5))
        tracker.process_line(parsed("M204 P4000"))
        self.assertEqual(tracker.state.print_acceleration_mm_s2, 1000.)
        tracker.process_line(parsed("M205 X6"))
        tracker.process_line(parsed("M205 J0"))
        self.assertEqual(tracker.state.jerk_x_mm_s, 6.)
        self.assertEqual(tracker.state.jerk_y_mm_s, 6.)

    def test_footer_minimum_feedrates_are_available_without_emitted_m205(self):
        limits = {"machine_min_extruding_rate": 3., "machine_min_travel_rate": 5.}
        trackers = (OrcaMachineStateTracker(OrcaTimingPolicy("marlin2", limits)),
                    PrusaMachineStateTracker(PrusaTimingPolicy("marlin2", limits), {}))
        for tracker in trackers:
            self.assertEqual(tracker.state.minimum_extruding_feedrate_mm_s, 3.)
            self.assertEqual(tracker.state.minimum_travel_feedrate_mm_s, 5.)

    def test_jd_is_gated_by_firmware_dialect_and_uses_current_units(self):
        tracker = OrcaMachineStateTracker(OrcaTimingPolicy("marlin", {"machine_max_jerk_x": 8.}))
        tracker.process_line(parsed("M205 J.02"))
        self.assertEqual(tracker.state.jerk_x_mm_s, 8.)
        tracker = OrcaMachineStateTracker(OrcaTimingPolicy("marlin2", {}))
        tracker.process_line(parsed("G20"))
        tracker.process_line(parsed("M205 J.001"))
        self.assertAlmostEqual(tracker.junction_deviation, .0254)

    def test_orca_klipper_limits_have_viewer_semantics(self):
        tracker = OrcaMachineStateTracker(OrcaTimingPolicy("klipper", {}))
        previous_retract = tracker.state.retract_acceleration_mm_s2
        tracker.process_line(parsed("SET_VELOCITY_LIMIT ACCEL=900 SQUARE_CORNER_VELOCITY=4 VELOCITY=80"))
        self.assertEqual(tracker.state.print_acceleration_mm_s2, 900.)
        self.assertEqual(tracker.state.travel_acceleration_mm_s2, 900.)
        self.assertEqual(tracker.state.retract_acceleration_mm_s2, previous_retract)
        self.assertEqual(tracker.state.jerk_x_mm_s, 4.)
        self.assertEqual(tracker.state.jerk_y_mm_s, 4.)
        self.assertEqual(tracker.state.maximum_feedrate_x_mm_s, 80.)

    def test_prusa_right_angle_junction_matches_geometric_equation(self):
        contexts = {}
        tracker = PrusaMachineStateTracker(PrusaTimingPolicy("marlin2", {}), contexts)
        for index, command in enumerate(("M83", "M204 P1000", "G1 X10 E.01 F6000", "G1 Y10 E.01 F6000")):
            event = tracker.process_line(parsed(command, index))
            if index == 2:
                previous = event
        actual = prusa_junction_speed(previous, event, 100., 100., 0., 0.,
                                      deviation=.01, acceleration_caps=(1000.,)*4)
        cosine = -.000001  # E / XYZ distance is .001 on each segment.
        sine = math.sqrt((1-cosine)/2)
        expected = math.sqrt(1000 * .01 * sine / (1-sine))
        self.assertAlmostEqual(actual, expected, places=10)
        reverse = tracker.process_line(parsed("G1 Y0 E.01 F6000", 5))
        self.assertAlmostEqual(prusa_junction_speed(event, reverse, 100., 100., 0., 0.,
            deviation=.01, acceleration_caps=(1000.,)*4), 0., delta=.1)

    def test_prusa_stream_context_is_bounded(self):
        contexts = {}
        tracker = PrusaMachineStateTracker(PrusaTimingPolicy("marlin2", {}), contexts)
        planner = PrusaMotionTimingPlanner(contexts)
        tracker.process_line(parsed("M83"))
        tracker.process_line(parsed("M204 P1000"))
        for index in range(900):
            event = tracker.process_line(parsed(f"G1 X{index*.1} E.01 F2400", index+10))
            planner.process_event(event)
            self.assertLessEqual(len(contexts), 257)
        planner.finish()
        self.assertEqual(contexts, {})

    @unittest.skipUnless(native_full_analysis_available(), "native engine unavailable")
    def test_native_python_parity_over_refresh_jd_reset_arcs_and_dwell(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "timing.gcode"
            for producer in ("OrcaSlicer", "PrusaSlicer"):
                for flavor in ("marlin2", "marlin", "klipper"):
                    with self.subTest(producer=producer, flavor=flavor):
                        path.write_bytes(timing_gcode(producer, flavor).encode())
                        original = path.read_bytes()
                        with patch.dict(os.environ, {"COOLING_TOWER_FORCE_PYTHON_ANALYSIS": "0"}):
                            service = GCodeAnalysisService()
                            native = service.analyze(path, force=True)
                            self.assertTrue(service.native_full_analysis_info["used"])
                        with patch.dict(os.environ, {"COOLING_TOWER_FORCE_PYTHON_ANALYSIS": "1"}):
                            reference = GCodeAnalysisService().analyze(path, force=True)
                        self.assertEqual(len(native.layers), len(reference.layers))
                        for a, b in zip(native.layers, reference.layers):
                            self.assertAlmostEqual(a.total_time_s, b.total_time_s, places=9)
                        self.assertEqual(path.read_bytes(), original)

    def test_cancellation_stops_each_policy(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "timing.gcode"
            for producer in ("OrcaSlicer", "PrusaSlicer"):
                path.write_bytes(timing_gcode(producer, "marlin2").encode())
                with self.assertRaises(AnalysisCancelled):
                    GCodeAnalysisService().analyze(path, force=True, cancellation_callback=lambda: True)
