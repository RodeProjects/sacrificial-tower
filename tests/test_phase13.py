def printable_gcode(*comments: str) -> str:
    return "\n".join(
        (
            *comments,
            "G90",
            "M83",
            "G1 Z0.2 F600",
            "G1 X10 E1 F600",
            "G1 Y10 E1 F600",
            "G1 Z0.4 F600",
            "G1 X20 E1 F600",
            "G1 Y20 E1 F600",
        )
    )


class Phase13MetadataTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)

    def tearDown(self) -> None:
        self.temporary.cleanup()

    def analyze(self, text: str, name: str = "model.gcode"):
        path = self.root / name
        path.write_text(text, encoding="utf-8")
        return GCodeAnalysisService().analyze(path, force=True)

    def test_explicit_slicer_name_version_family_and_source_line(self) -> None:
        snapshot = self.analyze(
            printable_gcode(
                "; generated by AnycubicSlicerNext 1.4.1.2 on a date"
            )
        )
        slicer = snapshot.metadata.slicer
        self.assertEqual(slicer.product_name, "AnycubicSlicerNext")
        self.assertEqual(slicer.version, "1.4.1.2")
        self.assertEqual(slicer.family, SlicerFamily.ORCA_BAMBU_ANYCUBIC)
        self.assertEqual(
            slicer.confidence,
            SlicerDetectionConfidence.EXPLICIT,
        )
        self.assertEqual(slicer.source_line, 1)
        generator = snapshot.metadata.values_for("generator_name")[0]
        self.assertEqual(generator.source_kind, MetadataSourceKind.HEADER_COMMENT)
        self.assertTrue(generator.explicit)

    def test_explicit_slicer_without_version_is_not_invented(self) -> None:
        snapshot = self.analyze(
            printable_gcode("; generated by PrusaSlicer")
        )
        self.assertEqual(snapshot.metadata.slicer.product_name, "PrusaSlicer")
        self.assertIsNone(snapshot.metadata.slicer.version)
        self.assertEqual(
            snapshot.metadata.slicer.family,
            SlicerFamily.PRUSA_SLIC3R,
        )

    def test_missing_generator_stays_unknown(self) -> None:
        snapshot = self.analyze(printable_gcode("; ordinary comment"))
        self.assertIsNone(snapshot.metadata.slicer.product_name)
        self.assertEqual(
            snapshot.metadata.slicer.confidence,
            SlicerDetectionConfidence.UNKNOWN,
        )

    def test_major_slicer_families_are_classified_without_guessing_printer(self) -> None:
        cases = (
            ("; generated by OrcaSlicer 2.3.0", "OrcaSlicer", SlicerFamily.ORCA_BAMBU_ANYCUBIC),
            ("; generated by BambuStudio-01.10.02.64", "Bambu Studio", SlicerFamily.ORCA_BAMBU_ANYCUBIC),
            ("; generated by PrusaSlicer 2.9.2", "PrusaSlicer", SlicerFamily.PRUSA_SLIC3R),
            ("; Generated with Cura_SteamEngine 5.10.0", "Cura", SlicerFamily.CURA),
            ("; Sliced by ideaMaker 5.2.3", "ideaMaker", SlicerFamily.IDEAMAKER),
            ("; G-Code generated by Simplify3D(R) Version 5.1.2", "Simplify3D", SlicerFamily.SIMPLIFY3D),
        )
        for index, (header, product, family) in enumerate(cases):
            with self.subTest(product=product):
                snapshot = self.analyze(
                    printable_gcode(header),
                    f"family_{index}.gcode",
                )
                self.assertEqual(snapshot.metadata.slicer.product_name, product)
                self.assertEqual(snapshot.metadata.slicer.family, family)
                self.assertEqual(
                    snapshot.metadata.slicer.confidence,
                    SlicerDetectionConfidence.EXPLICIT,
                )
                self.assertFalse(snapshot.metadata.values_for("printer_model"))

    def test_filename_hint_is_weak_and_never_overrides_explicit_header(self) -> None:
        weak = self.analyze(printable_gcode(), "OrcaSlicer_export.gcode")
        self.assertEqual(
            weak.metadata.slicer.confidence,
            SlicerDetectionConfidence.WEAK_SIGNATURE,
        )
        explicit = self.analyze(
            printable_gcode("; generated by PrusaSlicer 2.9.0"),
            "OrcaSlicer_export_2.gcode",
        )
        self.assertEqual(explicit.metadata.slicer.product_name, "PrusaSlicer")
        self.assertEqual(
            explicit.metadata.slicer.confidence,
            SlicerDetectionConfidence.EXPLICIT,
        )

    def test_config_block_preserves_known_and_unknown_values(self) -> None:
        snapshot = self.analyze(
            printable_gcode(
                "; CONFIG_BLOCK_START = begin",
                "; OrcaSlicer_config = begin",
                "; printer_model = Example M5",
                "; nozzle_diameter = 0.4,0.6",
                "; feature_enabled = true",
                "; overlap = 35%",
                "; filament_settings_id = \"PLA A\";\"PLA B\"",
                "; manufacturer_unknown_value = opaque payload",
                "; OrcaSlicer_config = end",
                "; CONFIG_BLOCK_END = end",
            )
        )
        metadata = snapshot.metadata
        self.assertEqual(
            metadata.slicer.confidence,
            SlicerDetectionConfidence.STRONG_SIGNATURE,
        )
        self.assertEqual(metadata.config_for("printer_model").value, "Example M5")
        self.assertEqual(
            metadata.config_for("nozzle_diameter").value,
            (0.4, 0.6),
        )
        self.assertIs(metadata.config_for("feature_enabled").value, True)
        overlap = metadata.config_for("overlap")
        self.assertEqual(overlap.value, 35)
        self.assertEqual(overlap.units, "%")
        self.assertEqual(
            metadata.config_for("filament_settings_id").value,
            ("PLA A", "PLA B"),
        )
        self.assertEqual(
            metadata.config_for("manufacturer_unknown_value").raw_value,
            "opaque payload",
        )

    def test_partial_standalone_configuration_is_captured(self) -> None:
        snapshot = self.analyze(
            printable_gcode(
                "; printer_settings_id = Custom machine",
                "; nozzle_diameter = 0.4",
            )
        )
        self.assertEqual(
            snapshot.metadata.config_for("printer_settings_id").value,
            "Custom machine",
        )
        self.assertEqual(
            snapshot.metadata.config_for("nozzle_diameter").value,
            0.4,
        )
        self.assertTrue(snapshot.metadata.profile_fingerprint.digest_sha256)

    def test_bambu_runtime_layer_height_does_not_replace_profile_value(self) -> None:
        cases = (
            ("0.16", "0.160007"),
            ("0.17", "0.169998"),
            ("0.18", "0.180008"),
            ("0.20", "0.200012"),
        )
        for index, (configured, runtime) in enumerate(cases):
            with self.subTest(configured=configured, runtime=runtime):
                snapshot = self.analyze(
                    printable_gcode(
                        "; generated by BambuStudio-02.08.02.61",
                        "; CONFIG_BLOCK_START = begin",
                        f"; layer_height = {configured}",
                        "; CONFIG_BLOCK_END = end",
                        "; CHANGE_LAYER",
                        f"; LAYER_HEIGHT: {runtime}",
                        f"; LAYER_HEIGHT: {runtime}",
                    ),
                    f"bambu_runtime_layer_{index}.gcode",
                )
                layer_values = tuple(
                    value
                    for value in snapshot.metadata.typed_config
                    if value.key == "layer_height"
                )
                self.assertEqual(len(layer_values), 1)
                self.assertEqual(layer_values[0].raw_value, configured)

    def test_later_config_block_supersedes_standalone_header_value(self) -> None:
        snapshot = self.analyze(
            printable_gcode(
                "; layer_height = 0.20",
                "; CONFIG_BLOCK_START = begin",
                "; layer_height = 0.18",
                "; CONFIG_BLOCK_END = end",
                "; LAYER_HEIGHT: 0.180008",
            ),
            "block_supersedes_header.gcode",
        )
        layer_values = tuple(
            value
            for value in snapshot.metadata.typed_config
            if value.key == "layer_height"
        )
        self.assertEqual(
            tuple(value.raw_value for value in layer_values),
            ("0.20", "0.18"),
        )
        self.assertEqual(snapshot.metadata.config_for("layer_height").value, 0.18)

    def test_custom_start_comment_does_not_become_verified_printer(self) -> None:
        snapshot = self.analyze(
            printable_gcode("; printer_model = User typed model text")
        )
        self.assertIsNone(snapshot.metadata.slicer.product_name)
        value = snapshot.metadata.values_for("printer_model")[0]
        self.assertEqual(value.value, "User typed model text")
        self.assertEqual(value.source_kind, MetadataSourceKind.HEADER_COMMENT)
        report = build_analysis_diagnostic_report(snapshot)
        self.assertFalse(report.exact_profile_verified)
        self.assertFalse(report.local_installation_verified)

    def test_marlin_and_klipper_commands_do_not_identify_a_slicer(self) -> None:
        marlin = self.analyze(
            printable_gcode("M115", "M201 X1000", "M204 S500"),
            "marlin.gcode",
        )
        klipper = self.analyze(
            printable_gcode(
                "SET_VELOCITY_LIMIT ACCEL=1200 SQUARE_CORNER_VELOCITY=5"
            ),
            "klipper.gcode",
        )
        self.assertIsNone(marlin.metadata.slicer.product_name)
        self.assertIsNone(klipper.metadata.slicer.product_name)
        hint = klipper.metadata.values_for("machine_command")[0]
        self.assertFalse(hint.explicit)
        self.assertEqual(hint.source_kind, MetadataSourceKind.MACHINE_COMMAND)

    def test_profile_names_and_effective_values_remain_separate(self) -> None:
        snapshot = self.analyze(
            printable_gcode(
                "; CONFIG_BLOCK_START = begin",
                "; printer_settings_id = Friendly profile name",
                "; outer_wall_speed = 58",
                "; machine_max_acceleration_x = 20000,10000",
                "; CONFIG_BLOCK_END = end",
            )
        )
        profile_name = snapshot.metadata.values_for("printer_settings_id")[0]
        speed = snapshot.metadata.config_for("outer_wall_speed")
        self.assertEqual(profile_name.value, "Friendly profile name")
        self.assertEqual(speed.value, 58)
        fingerprint_values = dict(
            snapshot.metadata.profile_fingerprint.values
        )
        self.assertNotIn("printer_settings_id", fingerprint_values)
        self.assertIn("outer_wall_speed", fingerprint_values)

    def test_scalar_list_percent_unit_and_quoted_values_are_typed(self) -> None:
        self.assertEqual(
            parse_typed_config_value("a", "12", source_line=1).value,
            12,
        )
        millimeters = parse_typed_config_value(
            "a", "0.42mm", source_line=1
        )
        self.assertEqual(millimeters.value, 0.42)
        self.assertEqual(millimeters.units, "mm")
        percentage = parse_typed_config_value(
            "a", "85%", source_line=1
        )
        self.assertEqual(percentage.value, 85)
        self.assertEqual(percentage.units, "%")
        listed = parse_typed_config_value(
            "nozzle_diameter", "0.4,0.6", source_line=1
        )
        self.assertEqual(listed.value, (0.4, 0.6))
        quoted = parse_typed_config_value(
            "a", '"001"', source_line=1
        )
        self.assertEqual(quoted.value, "001")
        quoted_list = parse_typed_config_value(
            "filament_settings_id",
            '"001";"002"',
            source_line=1,
        )
        self.assertEqual(quoted_list.value, ("001", "002"))
        invalid = parse_typed_config_value(
            "unknown_vendor_value",
            '"unterminated;value',
            source_line=7,
        )
        self.assertFalse(invalid.valid)
        self.assertEqual(invalid.raw_value, '"unterminated;value')
        self.assertIsNotNone(invalid.error)

    def test_fingerprint_is_stable_and_ignores_profile_display_name(self) -> None:
        first = self.analyze(
            printable_gcode(
                "; CONFIG_BLOCK_START = begin",
                "; printer_settings_id = First name",
                "; nozzle_diameter = 0.4",
                "; outer_wall_speed = 58",
                "; CONFIG_BLOCK_END = end",
            ),
            "first.gcode",
        )
        second = self.analyze(
            printable_gcode(
                "; CONFIG_BLOCK_START = begin",
                "; outer_wall_speed = 58",
                "; printer_settings_id = Renamed profile",
                "; nozzle_diameter = 0.4",
                "; CONFIG_BLOCK_END = end",
            ),
            "second.gcode",
        )
        self.assertEqual(
            first.metadata.profile_fingerprint.digest_sha256,
            second.metadata.profile_fingerprint.digest_sha256,
        )


class Phase13TimingEvidenceTests(unittest.TestCase):
    def test_timing_sources_are_not_conflated(self) -> None:
        source = LayerTimingState(
            layer_index=1,
            source_time_s=8.0,
            target_time_s=15.0,
            required_added_time_s=7.0,
        )
        sliced = replace(source, sliced_tower_time_s=5.0)
        final = replace(sliced, final_combined_time_s=14.5)
        self.assertEqual(source.best_evidence_kind, "source_gcode")
        self.assertEqual(source.best_available_combined_time_s, 8.0)
        self.assertEqual(sliced.best_evidence_kind, "sliced_tower")
        self.assertEqual(sliced.best_available_combined_time_s, 13.0)
        self.assertEqual(final.best_evidence_kind, "final_combined_gcode")
        self.assertEqual(final.best_available_combined_time_s, 14.5)

    def test_layer_state_builder_uses_exact_required_added_time(self) -> None:
        class Layer:
            index = 4
            total_time_s = 11.0

        state = build_layer_timing_states(
            (Layer(),),
            target_time_s=15.0,
            sliced_tower_times_s={4: 3.0},
        )[0]
        self.assertEqual(state.source_time_s, 11.0)
        self.assertEqual(state.required_added_time_s, 4.0)
        self.assertEqual(state.sliced_tower_time_s, 3.0)
        self.assertEqual(state.remaining_deficit_s, 1.0)

    def test_capacity_reduction_with_persistent_deficit_is_an_issue(self) -> None:
        states = (
            LayerTimingState(1, 11.0, 15.0, 4.0, sliced_tower_time_s=2.0),
            LayerTimingState(2, 11.0, 15.0, 4.0, sliced_tower_time_s=2.0),
        )
        issues = validate_time_capacity_transitions(
            states,
            {1: 3.0, 2: 2.0},
        )
        self.assertEqual(len(issues), 1)
        self.assertEqual(issues[0].layer_index, 2)

    def test_radius_may_shrink_if_time_capacity_does_not(self) -> None:
        states = (
            LayerTimingState(1, 11.0, 15.0, 4.0, sliced_tower_time_s=2.0),
            LayerTimingState(2, 11.0, 15.0, 4.0, sliced_tower_time_s=2.0),
        )
        self.assertEqual(
            validate_time_capacity_transitions(
                states,
                {1: 3.0, 2: 3.0},
            ),
            (),
        )

    def test_negative_or_nonfinite_timing_is_rejected(self) -> None:
        with self.assertRaises(ValueError):
            LayerTimingState(1, -1.0, 15.0, 4.0)
        with self.assertRaises(ValueError):
            LayerTimingState(1, 1.0, float("inf"), 4.0)


class Phase13CacheAndReportTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        self.source = self.root / "report.gcode"
        self.source.write_text(
            printable_gcode(
                "; generated by PrusaSlicer 2.9.0",
                "; CONFIG_BLOCK_START = begin",
                "; printer_model = Example",
                "; nozzle_diameter = 0.4",
                "; outer_wall_speed = 50",
                "; CONFIG_BLOCK_END = end",
            ),
            encoding="utf-8",
        )

    def tearDown(self) -> None:
        self.temporary.cleanup()

    def test_cache_rejects_old_parser_or_schema_snapshot(self) -> None:
        service = GCodeAnalysisService()
        current = service.analyze(self.source)
        legacy = replace(current, parser_version=0)
        self.assertFalse(legacy.matches_file())
        service._cache[current.gcode_path] = legacy
        refreshed = service.analyze(self.source)
        self.assertIsNot(refreshed, legacy)
        self.assertTrue(refreshed.matches_file())

    def test_diagnostic_report_labels_unverified_information(self) -> None:
        snapshot = GCodeAnalysisService().analyze(self.source)
        report = build_analysis_diagnostic_report(snapshot)
        text = format_analysis_diagnostic_report(report)
        self.assertIn("Generatorangabe im G-Code", text)
        self.assertIn("PrusaSlicer 2.9.0 (explicit)", text)
        self.assertIn("Lokale Installation verifiziert: nein", text)
        self.assertIn("Exakte Profilzuordnung verifiziert: nein", text)
        self.assertNotIn("Ihr Drucker ist", text)

    def test_report_roundtrip_and_future_version_rejection(self) -> None:
        snapshot = GCodeAnalysisService().analyze(self.source)
        report = AnalysisDiagnosticReport.from_snapshot(snapshot)
        restored = AnalysisDiagnosticReport.from_dict(report.to_dict())
        self.assertEqual(restored.metadata, report.metadata)
        self.assertEqual(restored.timing_evidence, report.timing_evidence)
        with self.assertRaises(UnsupportedAnalysisReportSchemaError):
            AnalysisDiagnosticReport.from_dict(
                {"analysis_report_schema_version": 999}
            )
        with self.assertRaises(UnsupportedMetadataSchemaError):
            GCodeMetadata.from_dict({"schema_version": 999})
        with self.assertRaises(UnsupportedMetadataSchemaError):
            GCodeMetadata.from_dict(
                {
                    "schema_version": 1,
                    "profile_fingerprint": {"schema_version": 999},
                }
            )

    def test_legacy_analysis_report_is_migrated_safely(self) -> None:
        restored = AnalysisDiagnosticReport.from_dict(
            {
                "source_gcode": "legacy.gcode",
                "layer_count": 2,
                "minimum_layer_time_s": 1.0,
                "maximum_layer_time_s": 2.0,
                "maximum_print_z_mm": 0.4,
                "generator_name": "LegacySlicer",
                "generator_version": "1.0",
                "printer_model": "Legacy Printer",
                "configuration": {
                    "nozzle_diameter": "0.4",
                },
            }
        )
        self.assertEqual(restored.schema_version, 1)
        self.assertEqual(
            restored.metadata.slicer.product_name,
            "LegacySlicer",
        )
        self.assertFalse(restored.exact_profile_verified)
        self.assertEqual(
            restored.metadata.values_for("printer_model")[0].value,
            "Legacy Printer",
        )

    def test_generation_run_writes_versioned_metadata_report(self) -> None:
        settings = GenerationSettings(target_layer_time_s=3.0)
        result = GenerationService(
            self.root / "output"
        ).generate(self.source, settings)
        self.assertIsInstance(result, GenerationResult)
        self.assertTrue(result.metadata_path.is_file())
        payload = json.loads(result.metadata_path.read_text(encoding="utf-8"))
        self.assertEqual(payload["analysis_report_schema_version"], 1)
        self.assertEqual(
            payload["metadata"]["slicer"]["product_name"],
            "PrusaSlicer",
        )
        summary = json.loads(result.summary_path.read_text(encoding="utf-8"))
        self.assertEqual(summary["analysis_report_schema_version"], 1)
        self.assertIn("profile_fingerprint", summary["gcode_metadata"])


class Phase13ReferenceRegressionTests(unittest.TestCase):
    def test_15_second_reference_case_is_machine_readable(self) -> None:
        payload = json.loads(REFERENCE_CASE.read_text(encoding="utf-8"))
        self.assertEqual(payload["target_layer_time_s"], 15.0)
        self.assertEqual(payload["observed_minimum_layer_time_s"], 11.0)
        self.assertEqual(payload["observed_minimum_shortfall_s"], 4.0)
        self.assertTrue(
            payload["observations"]["unexpected_profile_narrowing"]
        )
        self.assertTrue(
            payload["acceptance_rules"]
            ["capacity_must_not_shrink_while_deficit_remains"]
        )
        self.assertEqual(payload["source_fixture_status"], "removed")


