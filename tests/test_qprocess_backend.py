class _PythonFakeAdapter(BaseSlicerAdapter):
    adapter_id = "python_fake"
    product_name = "Python fake slicer"
    family = SlicerFamily.OTHER
    support_level = SlicerSupportLevel.FULL
    capabilities = frozenset({SlicerCapability.CLI_SLICE})

    def __init__(self, script: Path, *, mode: str = "slice", runner=None) -> None:
        super().__init__(runner=runner)
        self.script = script
        self.mode = mode

    def build_slice_command(self, request, model_path, output_directory, working_root):
        return Path(sys.executable), (
            str(self.script),
            self.mode,
            str(output_directory / "result.gcode"),
        )


class QProcessBackendTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.application = QApplication.instance() or QApplication([])

    def setUp(self) -> None:
        self.owner = tempfile.TemporaryDirectory()
        self.root = Path(self.owner.name) / "Pfad mit Leerzeichen ä"
        self.root.mkdir()
        self.script = self.root / "fake slicer.py"
        self.script.write_text(
            "\n".join(
                (
                    "import json, os, signal, sys, time",
                    "mode = sys.argv[1]",
                    "if mode == 'success':",
                    "    print('success')",
                    "elif mode == 'error':",
                    "    print('failure', file=sys.stderr)",
                    "    raise SystemExit(7)",
                    "elif mode == 'slicing-error':",
                    "    raise SystemExit(-100)",
                    "elif mode == 'invalid':",
                    "    sys.stdout.buffer.write(b'valid\\xfftail')",
                    "    sys.stdout.flush()",
                    "elif mode == 'large':",
                    "    sys.stdout.buffer.write(b'x' * (2 * 1024 * 1024))",
                    "    sys.stderr.buffer.write(b'y' * (1024 * 1024))",
                    "elif mode == 'environment':",
                    "    print(json.dumps({key: os.environ.get(key) for key in ('APPDATA', 'TEMP', 'COOLING_TOWER_SLICER_ISOLATED')}))",
                    "elif mode == 'error-mode':",
                    "    import ctypes",
                    "    print(int(ctypes.windll.kernel32.GetErrorMode()))",
                    "elif mode == 'hang':",
                    "    time.sleep(30)",
                    "elif mode == 'cancel-output':",
                    "    for index in range(10000):",
                    "        print(f'line-{index}', flush=True)",
                    "        time.sleep(0.001)",
                    "elif mode == 'crash':",
                    "    os.kill(os.getpid(), signal.SIGTERM)",
                    "elif mode == 'ntstatus':",
                    "    import ctypes",
                    "    exit_process = ctypes.windll.kernel32.ExitProcess",
                    "    exit_process.argtypes = (ctypes.c_uint32,)",
                    "    exit_process(0xC0000142)",
                    "elif mode == 'slice':",
                    "    from pathlib import Path",
                    "    Path(sys.argv[2]).write_text('; generated by Python fake\\n; filament used [mm] = 1\\nG90\\nM83\\nG1 Z0.2 F600\\nG1 X10 E1 F600\\nG1 Z0.4 F600\\nG1 X20 E1 F600\\n', encoding='utf-8')",
                    "elif mode == 'no-output':",
                    "    pass",
                )
            )
            + "\n",
            encoding="utf-8",
        )

    def tearDown(self) -> None:
        self.owner.cleanup()

    def run_backend(self, runner, mode: str, **kwargs):
        return runner.run(
            sys.executable,
            (self.script, mode),
            working_directory=self.root,
            timeout_s=kwargs.pop("timeout_s", 5.0),
            diagnostics_directory=self.root / "diagnostics",
            **kwargs,
        )

    @unittest.skipUnless(os.name == "nt", "Windows process policy")
    def test_qprocess_child_inherits_noninteractive_windows_error_mode(
        self,
    ) -> None:
        policy = configure_windows_process_policy()
        self.assertTrue(policy.active, policy)
        outcome = self.run_backend(QProcessSlicerProcessRunner(), "error-mode")
        self.assertEqual(outcome.return_code, 0, outcome)
        inherited_mode = int(outcome.stdout.strip())
        self.assertEqual(
            inherited_mode & WINDOWS_PROCESS_ERROR_MODE_FLAGS,
            WINDOWS_PROCESS_ERROR_MODE_FLAGS,
        )

    @unittest.skipUnless(os.name == "nt", "Windows NTSTATUS")
    def test_qprocess_high_ntstatus_is_classified_as_crash(self) -> None:
        outcome = self.run_backend(QProcessSlicerProcessRunner(), "ntstatus")
        self.assertTrue(outcome.crashed, outcome)
        self.assertEqual(windows_process_status(outcome.return_code), "0xC0000142")

    def test_success_error_invalid_utf8_and_crash_match_legacy_semantics(self) -> None:
        for mode in ("success", "error", "invalid", "crash"):
            with self.subTest(mode=mode):
                legacy = self.run_backend(SecureSlicerProcessRunner(), mode)
                qprocess = self.run_backend(QProcessSlicerProcessRunner(), mode)
                self.assertEqual(legacy.return_code == 0, qprocess.return_code == 0)
                self.assertEqual(legacy.timed_out, qprocess.timed_out)
                self.assertEqual(legacy.cancelled, qprocess.cancelled)
                self.assertEqual(
                    legacy.stdout.replace("\r\n", "\n"),
                    qprocess.stdout.replace("\r\n", "\n"),
                )
                self.assertEqual(
                    legacy.stderr.replace("\r\n", "\n"),
                    qprocess.stderr.replace("\r\n", "\n"),
                )

    @unittest.skipUnless(os.name == "nt", "Signed Windows application exits")
    def test_slicing_error_is_not_reported_as_a_windows_crash(self) -> None:
        for runner in (SecureSlicerProcessRunner(), QProcessSlicerProcessRunner()):
            with self.subTest(backend=runner.backend_name):
                outcome = self.run_backend(runner, "slicing-error")
                self.assertEqual(outcome.return_code & 0xFFFFFFFF, 0xFFFFFF9C)
                self.assertFalse(outcome.crashed, outcome)
                reason = BaseSlicerAdapter._failure_reason(outcome, ())
                self.assertIn("erste Schicht", reason)
                self.assertNotIn("abgestürzt", reason)

    def test_timeout_and_cross_thread_cancel_finish_before_return(self) -> None:
        timeout = self.run_backend(
            QProcessSlicerProcessRunner(termination_grace_ms=50),
            "hang",
            timeout_s=0.1,
        )
        self.assertTrue(timeout.timed_out)
        cancellation = threading.Event()
        timer = threading.Timer(0.05, cancellation.set)
        timer.start()
        try:
            cancelled = self.run_backend(
                QProcessSlicerProcessRunner(termination_grace_ms=50),
                "cancel-output",
                cancellation_event=cancellation,
            )
        finally:
            timer.join()
        self.assertTrue(cancelled.cancelled)
        self.assertIsNotNone(cancelled.return_code)

    def test_large_outputs_are_bounded_and_fully_archived(self) -> None:
        outcome = self.run_backend(
            QProcessSlicerProcessRunner(output_memory_limit_bytes=4096),
            "large",
        )
        self.assertTrue(outcome.stdout_truncated)
        self.assertTrue(outcome.stderr_truncated)
        self.assertLessEqual(len(outcome.stdout.encode("utf-8")), 4096)
        self.assertLessEqual(len(outcome.stderr.encode("utf-8")), 4096)
        self.assertIsNotNone(outcome.output_diagnostic_path)
        archive = outcome.output_diagnostic_path.read_bytes()
        self.assertGreaterEqual(archive.count(b"x"), 2 * 1024 * 1024)
        self.assertGreaterEqual(archive.count(b"y"), 1024 * 1024)

    def test_isolated_environment_lives_through_output_drain_then_is_removed(self) -> None:
        threads: list[QThread] = []

        def state_callback(_event, _details) -> None:
            threads.append(QThread.currentThread())

        from cooling_tower.slicers.process import ProcessRequest

        runner = QProcessSlicerProcessRunner()
        outcome = runner.run_request(
            ProcessRequest(
                executable=sys.executable,
                arguments=(self.script, "environment"),
                working_directory=self.root,
                timeout_s=5,
                diagnostics_directory=self.root / "diagnostics",
                state_callback=state_callback,
            )
        )
        values = json.loads(outcome.stdout)
        self.assertEqual(values["COOLING_TOWER_SLICER_ISOLATED"], "1")
        self.assertFalse(Path(values["APPDATA"]).exists())
        self.assertFalse(Path(values["TEMP"]).exists())
        self.assertTrue(threads)
        self.assertTrue(all(thread is threads[0] for thread in threads))

    def test_failing_state_observer_cannot_interrupt_process_supervision(self) -> None:
        def fail_observer(_event, _details) -> None:
            raise RuntimeError("observer failed")

        for runner in (
            SecureSlicerProcessRunner(),
            QProcessSlicerProcessRunner(),
        ):
            with self.subTest(backend=runner.backend_name):
                outcome = self.run_backend(
                    runner,
                    "success",
                    state_callback=fail_observer,
                )
                self.assertEqual(outcome.return_code, 0, outcome.stderr)

    def test_adapter_validation_runs_both_backends_in_separate_workspaces(self) -> None:
        model = self.root / "cube.stl"
        model.write_bytes(b"solid fake\nendsolid fake\n")
        installation = SlicerInstallation(
            adapter_id="python_fake",
            product_name="Python fake slicer",
            version="1",
            executable_path=Path(sys.executable),
            verified=True,
            capabilities=frozenset({SlicerCapability.CLI_SLICE}),
            discovery_source=SlicerDiscoverySource.MANUAL,
            family=SlicerFamily.OTHER,
            support_level=SlicerSupportLevel.FULL,
        )
        request = SliceRequest(
            model_path=model,
            profile=EffectiveProfile(installation, None, None, ()),
            output_directory=self.root / "unused-output",
            diagnostics_root=self.root / "validation-diagnostics",
            timeout_s=5,
        )
        report_path = self.root / "backend-validation.json"
        report = _PythonFakeAdapter(self.script).validate_process_backends(
            request,
            report_path=report_path,
        )
        self.assertTrue(report.equivalent, report.differences)
        self.assertEqual(report.adapter_id, "python_fake")
        self.assertTrue(report.legacy.gcode_readable)
        self.assertTrue(report.qprocess.gcode_readable)
        self.assertTrue(report_path.is_file())

        missing = _PythonFakeAdapter(
            self.script,
            mode="no-output",
        ).validate_process_backends(request)
        self.assertTrue(missing.equivalent, missing.differences)
        self.assertFalse(missing.legacy.success)
        self.assertFalse(missing.qprocess.success)


