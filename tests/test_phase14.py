class FakeAdapter(BaseSlicerAdapter):
    def __init__(
        self,
        adapter_id: str,
        product_name: str,
        family: SlicerFamily,
        *,
        support_level: SlicerSupportLevel = SlicerSupportLevel.FULL,
        timeout: bool = False,
        reject: bool = False,
    ) -> None:
        super().__init__()
        self.adapter_id = adapter_id
        self.product_name = product_name
        self.family = family
        self.support_level = support_level
        self.executable_names = (f"{adapter_id}.exe",)
        self.product_markers = (product_name, adapter_id)
        self.timeout = timeout
        self.reject = reject
        self.capabilities = (
            FULL_CAPABILITIES
            if support_level is SlicerSupportLevel.FULL
            else frozenset()
        )

    def verify_installation(self, candidate):
        if isinstance(candidate, Path):
            candidate = SlicerCandidate(
                candidate,
                SlicerDiscoverySource.MANUAL,
            )
        path = candidate.executable_path.resolve()
        if self.timeout:
            raise SlicerVerificationTimeoutError("probe timed out")
        if self.reject or "foreign" in path.stem.casefold():
            raise UnsupportedSlicerExecutableError("foreign executable")
        if not path.is_file():
            raise FileNotFoundError(path)
        return SlicerInstallation(
            adapter_id=self.adapter_id,
            product_name=self.product_name,
            version=candidate.version_hint,
            executable_path=path,
            verified=True,
            capabilities=self.capabilities,
            discovery_source=candidate.discovery_source,
            family=self.family,
            support_level=self.support_level,
        )


class ConfigurableRunner:
    def __init__(
        self,
        *,
        return_code: int = 0,
        create_gcode: bool = True,
        timed_out: bool = False,
        cancelled: bool = False,
    ) -> None:
        self.return_code = return_code
        self.create_gcode = create_gcode
        self.timed_out = timed_out
        self.cancelled = cancelled
        self.working_directory: Path | None = None

    def run(
        self,
        executable,
        arguments,
        *,
        working_directory,
        timeout_s,
        cancellation_event=None,
    ) -> ProcessOutcome:
        self.working_directory = Path(working_directory)
        command = (str(executable), *(str(item) for item in arguments))
        if self.create_gcode:
            index = list(arguments).index("--outputdir")
            output = Path(arguments[index + 1])
            output.mkdir(parents=True, exist_ok=True)
            (output / "plate_1.gcode").write_text(
                "; generated by Fake\nG90\nM83\n"
                "G1 Z0.2 F600\nG1 X10 E1 F600\n",
                encoding="utf-8",
            )
            (output / "plate_1.gcode.metadata").write_text(
                "{}\n",
                encoding="utf-8",
            )
        return ProcessOutcome(
            command=command,
            return_code=self.return_code,
            stdout="fake stdout",
            stderr="fake stderr" if self.return_code else "",
            duration_s=0.01,
            timed_out=self.timed_out,
            cancelled=self.cancelled,
        )


def make_executable(root: Path, name: str) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    path = root / name
    path.write_bytes(b"MZ phase14 test")
    return path


def source_identity(
    adapter_id: str,
    product: str,
    version: str | None,
    family: SlicerFamily,
) -> SlicerIdentity:
    return SlicerIdentity(
        product_name=product,
        version=version,
        family=family,
        adapter_id=adapter_id,
    )


