def source_gcode(layer_count: int = 4, *, x_offset: float = 0.0) -> str:
    lines = [
        "; generated by PrusaSlicer 2.9.0",
        "; CONFIG_BLOCK_START = begin",
        "; printer_model = Cache Test Printer",
        "; nozzle_diameter = 0.4",
        "; outer_wall_speed = 50",
        "; CONFIG_BLOCK_END = end",
        "G90",
        "M83",
        "M204 S1000",
    ]
    for layer in range(1, layer_count + 1):
        z = layer * 0.2
        x = x_offset + 10.0 + layer
        lines.append(f"G1 Z{z:.2f} F600")
        lines.append(f"G1 X{x:.3f} Y10.000 E0.4 F900")
        lines.append(f"G1 X{x + 1.0:.3f} Y11.000 E0.4 F900")
    return "\n".join(lines) + "\n"


def canonical_payload_hash(payload: object) -> str:
    serialized = json.dumps(
        payload,
        ensure_ascii=False,
        allow_nan=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(serialized).hexdigest()


class PersistentAnalysisCacheTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        self.source = self.root / "source.gcode"
        self.source.write_text(source_gcode(), encoding="utf-8")
        self.cache_path = self.root / "gcode_analysis_cache.json"

    def tearDown(self) -> None:
        self.temporary.cleanup()

    def analyze(self, source: Path | None = None):
        return GCodeAnalysisService(self.cache_path).analyze(
            source or self.source
        )

    def test_complete_snapshot_roundtrip_is_lossless(self) -> None:
        original = self.analyze()

        restored = PersistentGCodeAnalysisCache(self.cache_path).load()

        self.assertEqual(restored, original)
        self.assertEqual(restored.metadata, original.metadata)
        self.assertEqual(restored.timing_evidence, original.timing_evidence)
        self.assertEqual(restored.layers, original.layers)

    def test_new_service_reuses_cache_without_parsing(self) -> None:
        original = self.analyze()
        statuses: list[str] = []

        with patch.object(
            analysis_module,
            "iter_parsed_gcode_lines",
            side_effect=AssertionError("G-code must not be parsed again"),
        ):
            restored = GCodeAnalysisService(self.cache_path).analyze(
                self.source,
                progress_callback=lambda _percent, status: statuses.append(
                    status
                ),
            )

        self.assertEqual(restored, original)
        self.assertEqual(
            statuses,
            ["Persistente G-Code-Analyse wird verwendet"],
        )

    def test_different_successful_file_replaces_previous_reference(self) -> None:
        first = self.analyze()
        second_source = self.root / "second.gcode"
        second_source.write_text(
            source_gcode(layer_count=5, x_offset=20.0),
            encoding="utf-8",
        )

        second = self.analyze(second_source)
        persisted = PersistentGCodeAnalysisCache(self.cache_path).load()

        self.assertNotEqual(first.gcode_path, second.gcode_path)
        self.assertEqual(persisted, second)

    def test_changed_content_with_restored_metadata_is_reanalyzed(self) -> None:
        first = self.analyze()
        before = self.source.stat()
        original_text = self.source.read_text(encoding="utf-8")
        changed_text = original_text.replace("X11.000", "X91.000", 1)
        self.assertEqual(len(changed_text), len(original_text))
        self.source.write_text(changed_text, encoding="utf-8")
        os.utime(
            self.source,
            ns=(before.st_atime_ns, before.st_mtime_ns),
        )

        second = GCodeAnalysisService(self.cache_path).analyze(self.source)

        self.assertNotEqual(first.content_sha256, second.content_sha256)
        self.assertEqual(
            PersistentGCodeAnalysisCache(self.cache_path).load(),
            second,
        )

    def test_cancelled_analysis_does_not_replace_last_success(self) -> None:
        first = self.analyze()
        second_source = self.root / "cancelled.gcode"
        second_source.write_text(source_gcode(layer_count=5), encoding="utf-8")

        with self.assertRaises(AnalysisCancelled):
            GCodeAnalysisService(self.cache_path).analyze(
                second_source,
                cancellation_callback=lambda: True,
            )

        self.assertEqual(
            PersistentGCodeAnalysisCache(self.cache_path).load(),
            first,
        )

    def test_failed_analysis_does_not_replace_last_success(self) -> None:
        first = self.analyze()
        invalid_source = self.root / "invalid.gcode"
        invalid_source.write_text("G90\nG1 X10 F600\n", encoding="utf-8")

        with self.assertRaisesRegex(ValueError, "No printable layers"):
            GCodeAnalysisService(self.cache_path).analyze(invalid_source)

        self.assertEqual(
            PersistentGCodeAnalysisCache(self.cache_path).load(),
            first,
        )

    def test_corrupt_cache_is_ignored_and_repaired_after_analysis(self) -> None:
        self.cache_path.write_text('{"truncated":', encoding="utf-8")

        snapshot = GCodeAnalysisService(self.cache_path).analyze(self.source)

        self.assertEqual(
            PersistentGCodeAnalysisCache(self.cache_path).load(),
            snapshot,
        )

    def test_future_cache_schema_is_ignored_and_replaced(self) -> None:
        original = self.analyze()
        document = json.loads(self.cache_path.read_text(encoding="utf-8"))
        document["cache_schema_version"] = 999
        self.cache_path.write_text(json.dumps(document), encoding="utf-8")
        with self.assertRaises(UnsupportedPersistentAnalysisCacheError):
            PersistentGCodeAnalysisCache(self.cache_path).load()

        restored = GCodeAnalysisService(self.cache_path).analyze(self.source)
        repaired = json.loads(self.cache_path.read_text(encoding="utf-8"))

        self.assertEqual(restored, original)
        self.assertEqual(
            repaired["cache_schema_version"],
            PERSISTENT_ANALYSIS_CACHE_SCHEMA_VERSION,
        )

    def test_checksum_tampering_is_rejected(self) -> None:
        self.analyze()
        document = json.loads(self.cache_path.read_text(encoding="utf-8"))
        document["snapshot"]["file_size_bytes"] += 1
        self.cache_path.write_text(json.dumps(document), encoding="utf-8")

        with self.assertRaisesRegex(
            InvalidPersistentAnalysisCacheError,
            "checksum",
        ):
            PersistentGCodeAnalysisCache(self.cache_path).load()

    def test_semantic_tampering_is_rejected_even_with_new_checksum(self) -> None:
        self.analyze()
        document = json.loads(self.cache_path.read_text(encoding="utf-8"))
        document["snapshot"]["minimum_layer_time_s"] += 1.0
        document["payload_sha256"] = canonical_payload_hash(
            document["snapshot"]
        )
        self.cache_path.write_text(json.dumps(document), encoding="utf-8")

        with self.assertRaisesRegex(
            InvalidPersistentAnalysisCacheError,
            "minimum layer time",
        ):
            PersistentGCodeAnalysisCache(self.cache_path).load()

    def test_duplicate_json_fields_are_rejected(self) -> None:
        self.cache_path.write_text(
            '{"cache_schema_version":1,"cache_schema_version":1}',
            encoding="utf-8",
        )

        with self.assertRaisesRegex(
            InvalidPersistentAnalysisCacheError,
            "duplicate",
        ):
            PersistentGCodeAnalysisCache(self.cache_path).load()

    def test_pathological_json_number_is_treated_as_invalid_cache(self) -> None:
        self.cache_path.write_text(
            '{"cache_schema_version":' + "9" * 5_000 + "}",
            encoding="utf-8",
        )

        with self.assertRaisesRegex(
            InvalidPersistentAnalysisCacheError,
            "valid UTF-8 JSON",
        ):
            PersistentGCodeAnalysisCache(self.cache_path).load()

        snapshot = GCodeAnalysisService(self.cache_path).analyze(self.source)
        self.assertEqual(
            PersistentGCodeAnalysisCache(self.cache_path).load(),
            snapshot,
        )

    def test_oversized_cache_is_rejected_before_json_parsing(self) -> None:
        self.cache_path.write_bytes(b"x" * 65)

        with self.assertRaisesRegex(
            InvalidPersistentAnalysisCacheError,
            "too large",
        ):
            PersistentGCodeAnalysisCache(
                self.cache_path,
                maximum_bytes=64,
            ).load()

    def test_write_failure_does_not_fail_analysis_or_destroy_previous(self) -> None:
        first = self.analyze()
        second_source = self.root / "second.gcode"
        second_source.write_text(source_gcode(layer_count=5), encoding="utf-8")

        with patch(
            "cooling_tower.persistence.analysis_cache.atomic_write_json",
            side_effect=OSError("synthetic write failure"),
        ):
            second = GCodeAnalysisService(self.cache_path).analyze(
                second_source
            )

        self.assertEqual(second.layer_count, 5)
        self.assertEqual(
            PersistentGCodeAnalysisCache(self.cache_path).load(),
            first,
        )

    def test_atomic_write_leaves_no_temporary_files(self) -> None:
        self.analyze()

        self.assertEqual(
            tuple(self.root.glob(f".{self.cache_path.name}.*.tmp")),
            (),
        )

    def test_same_service_serializes_parallel_analysis_to_one_parse(self) -> None:
        service = GCodeAnalysisService(self.cache_path)
        original_parser = analysis_module.iter_parsed_gcode_lines

        with patch.object(
            analysis_module,
            "iter_parsed_gcode_lines",
            wraps=original_parser,
        ) as parser:
            with ThreadPoolExecutor(max_workers=8) as executor:
                snapshots = tuple(
                    executor.map(
                        lambda _index: service.analyze(self.source),
                        range(16),
                    )
                )

        self.assertEqual(parser.call_count, 1)
        self.assertTrue(all(item is snapshots[0] for item in snapshots))

    def test_cancelled_thread_releases_lock_for_waiting_analysis(self) -> None:
        service = GCodeAnalysisService(self.cache_path)
        cancellation_checked = Event()
        allow_cancellation = Event()

        def cancel_first() -> bool:
            cancellation_checked.set()
            allow_cancellation.wait(timeout=5.0)
            return True

        with ThreadPoolExecutor(max_workers=2) as executor:
            cancelled = executor.submit(
                service.analyze,
                self.source,
                cancellation_callback=cancel_first,
            )
            self.assertTrue(cancellation_checked.wait(timeout=5.0))
            waiting = executor.submit(service.analyze, self.source)
            allow_cancellation.set()

            with self.assertRaises(AnalysisCancelled):
                cancelled.result(timeout=5.0)
            snapshot = waiting.result(timeout=5.0)

        self.assertEqual(
            PersistentGCodeAnalysisCache(self.cache_path).load(),
            snapshot,
        )

    def test_multiple_services_write_one_valid_last_snapshot(self) -> None:
        second_source = self.root / "second.gcode"
        second_source.write_text(
            source_gcode(layer_count=5, x_offset=20.0),
            encoding="utf-8",
        )
        sources = (self.source, second_source)

        with ThreadPoolExecutor(max_workers=2) as executor:
            snapshots = tuple(
                executor.map(
                    lambda source: GCodeAnalysisService(
                        self.cache_path
                    ).analyze(source),
                    sources,
                )
            )

        persisted = PersistentGCodeAnalysisCache(self.cache_path).load()
        self.assertIn(persisted, snapshots)

    def test_invalid_maximum_size_configuration_is_rejected(self) -> None:
        for value in (0, -1, True, 1.5):
            with self.subTest(value=value):
                with self.assertRaisesRegex(ValueError, "positive integer"):
                    PersistentGCodeAnalysisCache(
                        self.cache_path,
                        maximum_bytes=value,  # type: ignore[arg-type]
                    )


class PersistentAnalysisCacheGuiIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.app = QApplication.instance() or QApplication([])

    def test_default_gui_service_uses_its_configuration_directory(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            window = MainWindow(
                user_settings_path=root / "settings.json",
                enable_update_check=False,
            )

            self.assertEqual(
                window.analysis_service.persistent_cache_path,
                (root / "gcode_analysis_cache.json").resolve(),
            )
            window.close()


