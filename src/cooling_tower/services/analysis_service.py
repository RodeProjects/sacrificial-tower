AnalysisProgressCallback = Callable[[int, str], None]
CancellationCallback = Callable[[], bool]
ParsedLineObserver = Callable[[ParsedGCodeLine], None]
AnalysisEventObserver = Callable[[ParsedGCodeLine, TimedSourceEvent], None]


def _native_product_owner(observer: Callable[..., object] | None) -> object | None:
    if observer is None:
        return None
    owner = getattr(observer, "__self__", None)
    if owner is None or not callable(getattr(owner, "consume_native", None)):
        return None
    return owner


def _native_product_request(
    line_observer: ParsedLineObserver | None,
    event_observers: tuple[AnalysisEventObserver, ...],
) -> tuple[object | None, object | None, int, str | None]:
    infill_owner: object | None = None
    preview_owner: object | None = None
    maximum_preview_segments = 60_000
    if line_observer is not None:
        owner = _native_product_owner(line_observer)
        if getattr(owner, "native_product_kind", None) != "infill":
            return None, None, maximum_preview_segments, "line_observer"
        infill_owner = owner
    if event_observers:
        if len(event_observers) != 1:
            return None, None, maximum_preview_segments, "event_observers"
        owner = _native_product_owner(event_observers[0])
        if getattr(owner, "native_product_kind", None) != "preview":
            return None, None, maximum_preview_segments, "event_observer"
        preview_owner = owner
        maximum_preview_segments = int(
            getattr(owner, "maximum_segments", maximum_preview_segments)
        )
    return (
        preview_owner,
        infill_owner,
        maximum_preview_segments,
        None,
    )


def _uses_bambu_studio_timing(source: Path) -> bool:
    """Detect Bambu-generated G-code before streaming motion analysis."""

    try:
        with source.open("rb") as handle:
            header = handle.read(16 * 1024).lower()
    except OSError:
        return False
    return b"bambustudio" in header or b"bambu studio" in header


def _uses_bambu_studio_layer_markers(source: Path) -> bool:
    """Detect Bambu's authoritative layer tags near the G-code start."""

    try:
        with source.open("rb") as handle:
            header = handle.read(1024 * 1024).lower()
    except OSError:
        return False
    return (
        (b"bambustudio" in header or b"bambu studio" in header)
        and b"; change_layer" in header
        and b"; z_height:" in header
        and b"; layer_height:" in header
    )


def _uses_anycubic_slicer_next(source: Path) -> bool:
    """Recognize the exact producer before allowing its startup macro."""

    try:
        with source.open("rb") as handle:
            header = handle.read(16 * 1024).lower()
    except OSError:
        return False
    return b"generated by anycubicslicernext" in header


def _uses_prusa_style_layer_markers(source: Path) -> bool:
    """Use nominal slicer layers even when a scarf seam ramps within one."""
    with source.open("rb") as handle:
        header = handle.read(1024 * 1024)
    return all(marker in header for marker in (b";LAYER_CHANGE", b";Z:", b";HEIGHT:"))


class AnalysisCancelled(RuntimeError):
    """Raised when an obsolete background analysis is cancelled."""


class GCodeChangedDuringAnalysisError(RuntimeError):
    """Raised when a source file changes while it is being parsed."""


class GCodeAnalysisService:
    """Analyze G-code once and reuse snapshots while the file is unchanged."""

    def __init__(
        self,
        persistent_cache_path: str | Path | None = None,
        *,
        block_cache_policy: BlockCachePolicy | str = BlockCachePolicy.AUTO,
        preprocessor_mode: bool = False,
    ) -> None:
        if preprocessor_mode and persistent_cache_path is not None:
            raise ValueError("Die separate Postprozessor-Zeitbasis verwendet keinen persistenten Analysecache.")
        self._preprocessor_mode = preprocessor_mode
        self._cache: dict[Path, GCodeAnalysisSnapshot] = {}
        self._lock = RLock()
        self._operation_lock = RLock()
        self._persistent_cache = (
            PersistentGCodeAnalysisCache(persistent_cache_path)
            if persistent_cache_path is not None
            else None
        )
        self._last_cache_hit_kind: str | None = None
        self._exact_block_cache = ExactGCodeBlockCache(
            policy=block_cache_policy
        )
        self._last_native_cache_stats: dict[str, int] | None = None
        self._last_native_analysis_info: dict[str, int | str | bool] | None = None

    @property
    def persistent_cache_path(self) -> Path | None:
        cache = self._persistent_cache
        return cache.path if cache is not None else None

    @property
    def exact_block_cache_info(self) -> dict[str, int | float | str | None]:
        return self._exact_block_cache.info()

    @property
    def native_block_cache_info(self) -> dict[str, int] | None:
        value = self._last_native_cache_stats
        return dict(value) if value is not None else None

    @property
    def native_full_analysis_info(self) -> dict[str, int | str | bool] | None:
        value = self._last_native_analysis_info
        return dict(value) if value is not None else None

    def analyze(
        self,
        gcode_path: str | Path,
        *,
        progress_callback: AnalysisProgressCallback | None = None,
        cancellation_callback: CancellationCallback | None = None,
        line_observer: ParsedLineObserver | None = None,
        event_observers: Iterable[AnalysisEventObserver] = (),
        force: bool = False,
    ) -> GCodeAnalysisSnapshot:
        # One service may be called by UI and worker threads. Serializing the
        # complete lookup/analysis/store transaction prevents duplicate
        # parsing and makes "last successful analysis" deterministic.
        observers = tuple(event_observers)
        with self._operation_lock:
            return self._analyze_locked(
                gcode_path,
                progress_callback=progress_callback,
                cancellation_callback=cancellation_callback,
                line_observer=line_observer,
                event_observers=observers,
                force=force,
            )

    def _analyze_locked(
        self,
        gcode_path: str | Path,
        *,
        progress_callback: AnalysisProgressCallback | None,
        cancellation_callback: CancellationCallback | None,
        line_observer: ParsedLineObserver | None,
        event_observers: tuple[AnalysisEventObserver, ...],
        force: bool,
    ) -> GCodeAnalysisSnapshot:
        source = validate_gcode_path(gcode_path).resolve()
        before = source.stat()
        notify = progress_callback or (lambda percent, status: None)
        cancelled = cancellation_callback or (lambda: False)

        if not force and line_observer is None and not event_observers:
            cached = self._get_cached_locked(source)
            if cached is not None:
                status = (
                    "Persistente G-Code-Analyse wird verwendet"
                    if self._last_cache_hit_kind == "persistent"
                    else "Zwischengespeicherte G-Code-Analyse wird verwendet"
                )
                notify(
                    100,
                    status,
                )
                return cached

        notify(0, "G-Code wird analysiert")
        analysis_started = time.perf_counter()
        self._last_native_cache_stats = None
        self._last_native_analysis_info = None
        native_cache_before = native_timing_cache_info()
        bambu_timing = _uses_bambu_studio_timing(source)
        anycubic_slicer_next = _uses_anycubic_slicer_next(source)
        orca_policy = read_orca_timing_policy(source)
        prusa_policy = read_prusa_timing_policy(source)
        explicit_bambu_layers = _uses_bambu_studio_layer_markers(source)
        with source.open("rb") as stream:
            analysis_header = stream.read(16 * 1024)
        producer_header = analysis_header.lower()
        preprocessor_header = any(marker in analysis_header[:1024] for marker in (
            b"; SACRIFICIAL_TOWER_POSTPROCESSED", b"; SACRIFICIAL_TOWER_PREPROCESSED"))
        prusa_source = b"generated by prusaslicer " in producer_header
        prusa_style_source = prusa_source or anycubic_slicer_next or b"generated by orcaslicer " in producer_header
        explicit_prusa_layers = (prusa_style_source and _uses_prusa_style_layer_markers(source)
            or prusa_source and (self._preprocessor_mode or preprocessor_header))
        (
            preview_owner,
            infill_owner,
            maximum_preview_segments,
            observer_fallback_reason,
        ) = _native_product_request(line_observer, event_observers)
        if (
            observer_fallback_reason is None
            and self._exact_block_cache.policy is not BlockCachePolicy.AUTO
        ):
            observer_fallback_reason = (
                f"block_cache_policy:{self._exact_block_cache.policy.value}"
            )
        native_result: NativeAnalysisResult | None = None
        if observer_fallback_reason is None:
            try:
                native_result = analyze_native_gcode(
                    source,
                    bambu_compatible=bambu_timing,
                    anycubic_slicer_next_compatible=anycubic_slicer_next,
                    use_explicit_layer_markers=explicit_bambu_layers or explicit_prusa_layers,
                    collect_preview=preview_owner is not None,
                    maximum_preview_segments=maximum_preview_segments,
                    collect_infill=infill_owner is not None,
                    cancellation_callback=cancelled,
                    **({"orca_policy": orca_policy} if orca_policy is not None else {}),
                    **({"prusa_policy": prusa_policy} if prusa_policy is not None else {}),
                )
            except NativeAnalysisCancelled as error:
                raise AnalysisCancelled(str(error)) from error

        native_used = native_result is not None and native_result.succeeded
        if native_used:
            assert native_result is not None
            assert native_result.analysis is not None
            assert native_result.metadata is not None
            assert native_result.timing_evidence is not None
            if preview_owner is not None:
                preview_owner.consume_native(native_result.preview)
            if infill_owner is not None:
                infill_owner.consume_native(native_result.infill)
            analysis = native_result.analysis
            metadata = native_result.metadata
            timing_evidence = native_result.timing_evidence
            self._last_native_analysis_info = {
                "used": True,
                "status": native_result.status,
                **dict(native_result.diagnostics or {}),
            }
            notify(95, "Native G-Code-Analyse wird zusammengefasst")
        else:
            fallback_status = (
                f"observer:{observer_fallback_reason}"
                if observer_fallback_reason is not None
                else native_result.status
                if native_result is not None
                else "unavailable"
            )
            self._last_native_analysis_info = {
                "used": False,
                "status": fallback_status,
                "fallback_line": (
                    native_result.fallback_line
                    if native_result is not None
                    else 0
                ),
                "fallback_command": (
                    native_result.fallback_command
                    if native_result is not None
                    else ""
                ),
            }
            record_diagnostic(
                "gcode_native_full_analysis_fallback",
                status=fallback_status,
                fallback_line=(
                    native_result.fallback_line
                    if native_result is not None
                    else 0
                ),
                fallback_command=(
                    native_result.fallback_command
                    if native_result is not None
                    else ""
                ),
            )
            analysis, metadata, timing_evidence = self._analyze_python_stream(
                source,
                workload_bytes=before.st_size,
                bambu_timing=bambu_timing,
                explicit_bambu_layers=explicit_bambu_layers,
                notify=notify,
                cancelled=cancelled,
                line_observer=line_observer,
                event_observers=event_observers,
                orca_policy=orca_policy,
                prusa_policy=prusa_policy,
                explicit_prusa_layers=explicit_prusa_layers,
            )

        if cancelled():
            raise AnalysisCancelled("G-Code analysis was cancelled.")

        notify(97, "Layerzeiten und Konfiguration werden zusammengefasst")
        if not analysis.layers:
            raise ValueError("No printable layers were detected in the G-code.")

        if anycubic_slicer_next and not self._preprocessor_mode:
            native_times = read_slicer_layer_times(source)
            if native_times is not None:
                if len(native_times.times_s) != len(analysis.layers) or any(
                    abs(layer.z_mm - z) > 0.01
                    for layer, z in zip(analysis.layers, native_times.z_values_mm)
                ):
                    raise ValueError(
                        "Die nativen Slicer-Layerzeiten stimmen nicht mit den G-Code-Layern überein."
                    )
                # Full layer times are authoritative slicer data. The motion
                # components remain estimates for the initial geometry model;
                # they do not determine convergence or displayed result times.
                analysis = replace(
                    analysis,
                    layers=tuple(
                        replace(layer, total_time_s=duration)
                        for layer, duration in zip(analysis.layers, native_times.times_s)
                    ),
                )
                record_diagnostic(
                    "slicer_native_layer_times",
                    adapter="anycubic_slicer_next",
                    layer_count=len(native_times.times_s),
                    minimum_layer_time_s=min(native_times.times_s),
                    clock_resolution_s=0.001,
                )

        after = source.stat()
        if (
            after.st_size != before.st_size
            or after.st_mtime_ns != before.st_mtime_ns
        ):
            raise GCodeChangedDuringAnalysisError(
                "The G-code file changed while it was being analyzed."
            )

        notify(98, "G-Code-Inhalt wird für die Wiederverwendung geprüft")
        try:
            content_sha256 = sha256_file(source)
            after_hash = source.stat()
        except OSError as error:
            raise GCodeChangedDuringAnalysisError(
                "The G-code file became unavailable while it was being hashed."
            ) from error
        if (
            after_hash.st_size != after.st_size
            or after_hash.st_mtime_ns != after.st_mtime_ns
        ):
            raise GCodeChangedDuringAnalysisError(
                "The G-code file changed while it was being hashed."
            )
        after = after_hash

        layers = analysis.layers
        snapshot = GCodeAnalysisSnapshot(
            gcode_path=source,
            file_size_bytes=after.st_size,
            file_modified_ns=after.st_mtime_ns,
            analysis=analysis,
            minimum_layer_time_s=min(
                layer.total_time_s for layer in layers
            ),
            maximum_layer_time_s=max(
                layer.total_time_s for layer in layers
            ),
            maximum_print_z_mm=layers[-1].z_mm,
            global_seconds_per_deposition_mm=(
                calculate_seconds_per_deposition_mm(layers)
            ),
            metadata=metadata,
            timing_evidence=timing_evidence,
            content_sha256=content_sha256,
        )
        with self._lock:
            self._cache[source] = snapshot
        persistent_cache = self._persistent_cache
        if persistent_cache is not None:
            try:
                persistent_cache.save(snapshot)
            except (OSError, PersistentAnalysisCacheError) as error:
                record_diagnostic(
                    "persistent_analysis_cache_write_failed",
                    error_type=type(error).__name__,
                )
            else:
                record_diagnostic(
                    "persistent_analysis_cache_stored",
                    layer_count=snapshot.layer_count,
                    file_size_bytes=snapshot.file_size_bytes,
                )
        analysis_duration_s = max(0.0, time.perf_counter() - analysis_started)
        if native_used:
            cache_stats = None
        else:
            self._exact_block_cache.record_analysis_time(analysis_duration_s)
            cache_stats = self._exact_block_cache.last_analysis_stats()
        native_cache_after = native_timing_cache_info()
        native_deltas = {
            key: native_cache_after.get(key, 0) - native_cache_before.get(key, 0)
            for key in ("hits", "misses", "evictions")
        }
        native_deltas.update(
            {
                "entries_before": native_cache_before.get("entries", 0),
                "entries_after": native_cache_after.get("entries", 0),
                "bytes_before": native_cache_before.get("bytes", 0),
                "bytes_after": native_cache_after.get("bytes", 0),
            }
        )
        self._last_native_cache_stats = native_deltas
        if cache_stats is not None:
            record_diagnostic(
                "gcode_python_block_cache_analysis",
                configured_policy=cache_stats.configured_policy.value,
                effective_policy=cache_stats.effective_policy.value,
                bypass_reason=cache_stats.bypass_reason,
                hits=cache_stats.hits,
                misses=cache_stats.misses,
                evictions=cache_stats.evictions,
                processed_blocks=cache_stats.processed_blocks,
                occupied_bytes=cache_stats.occupied_bytes_after,
                avoided_insertions=cache_stats.avoided_insertions,
                estimated_avoided_bytes=cache_stats.estimated_avoided_bytes,
                cache_time_s=cache_stats.cache_time_s,
                analysis_time_s=analysis_duration_s,
            )
        record_diagnostic(
            "gcode_native_planning_cache_analysis",
            policy=(
                "bypassed_by_full_native_analysis"
                if native_used
                else "independent_enabled"
            ),
            **native_deltas,
        )
        if native_used:
            record_diagnostic(
                "gcode_native_full_analysis",
                **dict(self._last_native_analysis_info or {}),
            )
        notify(100, "G-Code-Analyse abgeschlossen")
        return snapshot

    def _analyze_python_stream(
        self,
        source: Path,
        *,
        workload_bytes: int,
        bambu_timing: bool,
        explicit_bambu_layers: bool,
        notify: AnalysisProgressCallback,
        cancelled: CancellationCallback,
        line_observer: ParsedLineObserver | None,
        event_observers: tuple[AnalysisEventObserver, ...],
        orca_policy=None,
        prusa_policy=None,
        explicit_prusa_layers=False,
    ) -> tuple[LayerAnalysis, GCodeMetadata, TimingEvidence]:
        """Run the unchanged reference semantics after a native fallback."""
        tracker = (OrcaMachineStateTracker(orca_policy) if orca_policy is not None
                   else MachineStateTracker(bambu_compatible=bambu_timing))
        motion_planner = OrcaMotionTimingPlanner() if orca_policy is not None else MotionTimingPlanner(
            bambu_compatible=bambu_timing
        )
        if prusa_policy is not None:
            contexts = {}
            tracker = PrusaMachineStateTracker(prusa_policy, contexts)
            motion_planner = PrusaMotionTimingPlanner(contexts)
        detector = LayerDetector(
            use_explicit_markers=explicit_bambu_layers or explicit_prusa_layers
        )
        metadata_collector = GCodeMetadataCollector(source)
        pending_layer_start_line: int | None = None
        pending_layer_z_mm: float | None = None
        processed_bytes = 0
        last_reported_percent = 0
        parsed_lines = iter_parsed_gcode_lines(source)
        events = (
            ((line, tracker.process_line(line)) for line in parsed_lines)
            if orca_policy is not None or prusa_policy is not None else self._exact_block_cache.iter_events(
                parsed_lines, tracker, workload_bytes=workload_bytes,
            )
        )
        try:
            for parsed_line, event in events:
                if parsed_line.number % 256 == 0 and cancelled():
                    raise AnalysisCancelled("G-Code analysis was cancelled.")
                if line_observer is not None:
                    line_observer(parsed_line)
                for observer in event_observers:
                    observer(parsed_line, event)
                processed_bytes += len(parsed_line.raw_text) + 1
                if parsed_line.number % 2_000 == 0 and workload_bytes > 0:
                    percent = min(
                        95,
                        max(1, round(processed_bytes / workload_bytes * 95)),
                    )
                    if percent > last_reported_percent:
                        last_reported_percent = percent
                        notify(percent, "G-Code-Inhalt wird ausgewertet")
                metadata_collector.consume(parsed_line)
                if explicit_bambu_layers or explicit_prusa_layers:
                    comment = (parsed_line.comment or "").strip()
                    prusa_style = explicit_prusa_layers
                    if comment == ("LAYER_CHANGE" if prusa_style else "CHANGE_LAYER"):
                        pending_layer_start_line = parsed_line.number
                        pending_layer_z_mm = None
                    elif (
                        pending_layer_start_line is not None
                        and comment.startswith("Z:" if prusa_style else "Z_HEIGHT:")
                    ):
                        try:
                            pending_layer_z_mm = float(
                                comment.partition(":")[2].strip()
                            )
                        except ValueError:
                            pending_layer_start_line = None
                            pending_layer_z_mm = None
                    elif (
                        pending_layer_start_line is not None
                        and pending_layer_z_mm is not None
                        and comment.startswith("HEIGHT:" if prusa_style else "LAYER_HEIGHT:")
                    ):
                        try:
                            layer_height_mm = float(
                                comment.partition(":")[2].strip()
                            )
                        except ValueError:
                            pending_layer_start_line = None
                            pending_layer_z_mm = None
                        else:
                            detector.mark_layer(
                                start_line=pending_layer_start_line,
                                z_mm=pending_layer_z_mm,
                                height_mm=layer_height_mm,
                            )
                            pending_layer_start_line = None
                            pending_layer_z_mm = None
                if event is not None:
                    for timed_event in motion_planner.process_event(event):
                        detector.process_event(timed_event)

        finally:
            parsed_lines.close()

        for timed_event in motion_planner.finish():
            detector.process_event(timed_event)
        if cancelled():
            raise AnalysisCancelled("G-Code analysis was cancelled.")
        analysis = detector.finish()
        metadata, timing_evidence = metadata_collector.finish()
        return analysis, metadata, timing_evidence

    def get_cached(
        self,
        gcode_path: str | Path,
    ) -> GCodeAnalysisSnapshot | None:
        with self._operation_lock:
            return self._get_cached_locked(gcode_path)

    def _get_cached_locked(
        self,
        gcode_path: str | Path,
    ) -> GCodeAnalysisSnapshot | None:
        self._last_cache_hit_kind = None
        try:
            source = Path(gcode_path).expanduser().resolve(strict=True)
        except (FileNotFoundError, OSError):
            return None
        with self._lock:
            snapshot = self._cache.get(source)
        if snapshot is not None:
            if self._snapshot_matches_source(snapshot, source):
                self._last_cache_hit_kind = "memory"
                record_diagnostic("gcode_analysis_memory_cache_hit")
                return snapshot
            with self._lock:
                self._cache.pop(source, None)

        persistent_cache = self._persistent_cache
        if persistent_cache is None:
            return None
        try:
            persisted = persistent_cache.load()
        except (OSError, PersistentAnalysisCacheError) as error:
            record_diagnostic(
                "persistent_analysis_cache_load_failed",
                error_type=type(error).__name__,
            )
            return None
        if persisted is None:
            record_diagnostic("persistent_analysis_cache_miss", reason="absent")
            return None
        if not self._snapshot_matches_source(persisted, source):
            record_diagnostic(
                "persistent_analysis_cache_miss",
                reason="source_version_mismatch",
            )
            return None
        with self._lock:
            self._cache[source] = persisted
        self._last_cache_hit_kind = "persistent"
        record_diagnostic(
            "persistent_analysis_cache_hit",
            layer_count=persisted.layer_count,
            file_size_bytes=persisted.file_size_bytes,
        )
        return persisted

    @staticmethod
    def _snapshot_matches_source(
        snapshot: GCodeAnalysisSnapshot,
        source: Path,
    ) -> bool:
        if not snapshot.matches_file(source):
            return False
        expected_digest = snapshot.content_sha256
        if expected_digest is None:
            return False
        try:
            before = source.stat()
            actual_digest = sha256_file(source)
            after = source.stat()
        except OSError:
            return False
        return (
            before.st_size == after.st_size == snapshot.file_size_bytes
            and before.st_mtime_ns
            == after.st_mtime_ns
            == snapshot.file_modified_ns
            and snapshot.matches_file(source)
            and compare_digest(
                actual_digest,
                str(expected_digest).casefold(),
            )
        )

    def invalidate(self, gcode_path: str | Path | None = None) -> None:
        with self._operation_lock:
            with self._lock:
                if gcode_path is None:
                    self._cache.clear()
                    return
                try:
                    source = Path(gcode_path).expanduser().resolve()
                except OSError:
                    return
                self._cache.pop(source, None)
