"""Prusa-specific classic-jerk and geometric junction-deviation timing."""
from __future__ import annotations

import math
import re
from dataclasses import dataclass
from pathlib import Path

from cooling_tower.gcode.parser import (
    MachineStateTracker, MotionTimingPlanner, Movement,
    _bambu_axis_feedrates, _bambu_safe_feedrate, _bambu_timing_distance,
)
from cooling_tower.gcode.window_planner import plan_window


@dataclass(frozen=True, slots=True)
class PrusaTimingPolicy:
    flavor: str
    limits: dict[str, float]

    @property
    def uses_junction_deviation(self) -> bool:
        return self.flavor == "marlin2"


def read_prusa_timing_policy(source: Path) -> PrusaTimingPolicy | None:
    with source.open("rb") as stream:
        if b"generated by prusaslicer " not in stream.read(16384).lower():
            return None
        stream.seek(0, 2)
        stream.seek(max(0, stream.tell() - 1024 * 1024))
        tail = stream.read().decode("utf-8", errors="replace")
    flavor, limits = "", {}
    for key, text in re.findall(
        r"^; (gcode_flavor|machine_(?:max|minimum|min)_[a-z_]+) = ([^\r\n]+)\r?$",
        tail, re.MULTILINE,
    ):
        if key == "gcode_flavor":
            flavor = text.strip().strip('"').casefold()
            continue
        try:
            value = float(text.split(",", 1)[0].strip().strip('"'))
        except ValueError:
            continue
        if math.isfinite(value) and value >= 0:
            limits[key] = value
    return PrusaTimingPolicy(flavor, limits) if flavor in {"marlin", "marlin2"} else None


class PrusaMachineStateTracker(MachineStateTracker):
    def __init__(self, policy: PrusaTimingPolicy, contexts: dict):
        super().__init__(bambu_compatible=True)
        self.policy = policy
        self.contexts = contexts
        self.junction_deviation = policy.limits.get("machine_max_junction_deviation", 0.)
        self.state.minimum_extruding_feedrate_mm_s = policy.limits.get("machine_min_extruding_rate")
        self.state.minimum_travel_feedrate_mm_s = policy.limits.get("machine_min_travel_rate")
        for category, key, fallback in (
            ("print", "extruding", 1500.), ("travel", "travel", 1250.),
            ("retract", "retracting", 1500.),
        ):
            setattr(self.state, f"{category}_acceleration_mm_s2",
                    policy.limits.get(f"machine_max_acceleration_{key}") or fallback)
        for axis in "xyze":
            setattr(self.state, f"maximum_acceleration_{axis}_mm_s2",
                    policy.limits.get(f"machine_max_acceleration_{axis}"))
            setattr(self.state, f"maximum_feedrate_{axis}_mm_s",
                    policy.limits.get(f"machine_max_feedrate_{axis}"))
            setattr(self.state, f"jerk_{axis}_mm_s",
                    policy.limits.get(f"machine_max_jerk_{axis}"))

    def process_line(self, parsed):
        if parsed.command == "M205" and "J" in parsed.parameters:
            self.junction_deviation = max(0., parsed.parameters["J"] * self.state.unit_scale_mm)
        event = super().process_line(parsed)
        if isinstance(event, Movement):
            self.contexts[event.line_number] = (
                self.junction_deviation if self.policy.uses_junction_deviation else 0.,
                tuple(getattr(self.state, f"maximum_acceleration_{axis}_mm_s2") for axis in "xyze"),
            )
        return event


def prusa_junction_speed(previous, current, previous_speed, current_speed,
                         previous_safe, current_safe, *, deviation=0., acceleration_caps=()):
    if min(previous_speed, current_speed) <= 1e-9:
        return current_safe
    if deviation > 0:
        before = tuple(value / _bambu_timing_distance(previous) for value in (
            previous.delta_x, previous.delta_y, previous.delta_z, previous.delta_e))
        after = tuple(value / _bambu_timing_distance(current) for value in (
            current.delta_x, current.delta_y, current.delta_z, current.delta_e))
        cosine = -sum(a * b for a, b in zip(before, after))
        if cosine > .999999:
            return 0.
        cosine = max(-.999999, cosine)
        change = tuple(b-a for a, b in zip(before, after))
        magnitude = math.sqrt(sum(value * value for value in change))
        acceleration = current.acceleration_mm_s2 or 0.
        if magnitude > 1e-9:
            for cap, component in zip(acceleration_caps, change):
                if cap and abs(component) > 1e-9:
                    acceleration = min(acceleration, cap * magnitude / abs(component))
        half_sine = math.sqrt((1-cosine) / 2)
        speed_squared = acceleration * deviation * half_sine / (1-half_sine)
        distance = _bambu_timing_distance(current)
        if distance < 1. and cosine < -math.sqrt(.5):
            # The exact angle avoids embedding the slicer's approximation
            # polynomial; its .033-radian floor is part of the speed policy.
            speed_squared = min(speed_squared, distance * acceleration / max(.033, math.acos(-cosine)))
        return math.sqrt(max(0., min(speed_squared, previous_speed**2, current_speed**2)))

    shared = min(previous_speed, current_speed)
    before = _bambu_axis_feedrates(previous, shared)
    after = _bambu_axis_feedrates(current, current_speed)
    factor = 1.
    for a, b, cap in zip(before, after, (
        current.jerk_x_mm_s, current.jerk_y_mm_s, current.jerk_z_mm_s, current.jerk_e_mm_s,
    )):
        a, b = a * factor, b * factor
        change = abs(a-b) if a*b > 0 else max(abs(a), abs(b))
        if cap is not None and change > cap:
            factor *= cap / change
    speed = shared * factor
    return current_safe if min(previous_safe, current_safe) > speed * .99 else speed


class PrusaMotionTimingPlanner(MotionTimingPlanner):
    def __init__(self, contexts: dict):
        super().__init__(bambu_compatible=True, refresh_threshold_movements=256)
        self.contexts = contexts

    def _planned_pending(self):
        def junction(previous, current, *speeds):
            deviation, caps = self.contexts[current.line_number]
            return prusa_junction_speed(previous, current, *speeds,
                                        deviation=deviation, acceleration_caps=caps)

        def safe(movement, speed):
            return 0. if self.contexts[movement.line_number][0] > 0 else _bambu_safe_feedrate(movement, speed)

        movements = [event for event in self._pending_events if self._is_plannable(event)]
        planned = iter(plan_window(movements, junction_speed=junction, safe_speed=safe,
            start_speed=self._start_speed_mm_s, previous=self._previous_physical_movement,
            cache=self._kinematics_cache))
        return [next(planned) if self._is_plannable(event) else event for event in self._pending_events]

    def process_event(self, event):
        emitted = super().process_event(event)
        for movement in emitted:
            self.contexts.pop(movement.line_number, None)
        return emitted

    def finish(self):
        result = super().finish()
        self.contexts.clear()
        return result
