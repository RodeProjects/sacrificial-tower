"""Orca-only machine limits and motion transitions for its layer-time view.

This is independent application code. Orca is an external executable; no slicer
implementation or runtime library is embedded. Other producers keep their
existing motion policies.
"""
from __future__ import annotations

import math
import re
from dataclasses import dataclass
from pathlib import Path

from cooling_tower.gcode.window_planner import plan_window
from cooling_tower.gcode.parser import (
    MOVEMENT_EPSILON, MachineStateTracker, MotionTimingPlanner,
    _bambu_axis_feedrates,
)


@dataclass(frozen=True, slots=True)
class OrcaTimingPolicy:
    flavor: str
    limits: dict[str, float]

    @property
    def uses_junction_deviation(self) -> bool:
        return self.flavor == "marlin2"


def read_orca_timing_policy(source: Path) -> OrcaTimingPolicy | None:
    with source.open("rb") as stream:
        header = stream.read(16384).lower()
        if b"generated by orcaslicer " not in header:
            return None
        stream.seek(0, 2)
        size = stream.tell()
        stream.seek(max(0, size - 1024 * 1024))
        tail = stream.read().decode("utf-8", errors="replace")
    flavor = ""
    limits = {}
    for key, text in re.findall(
        r"^; (gcode_flavor|machine_(?:max|minimum|min)_[a-z_]+) = ([^\r\n]+)\r?$",
        tail, re.MULTILINE,
    ):
        if key == "gcode_flavor":
            flavor = text.strip().strip('"').casefold()
        else:
            try:
                value = float(text.split(",", 1)[0].strip().strip('"'))
            except ValueError:
                continue
            if math.isfinite(value) and value >= 0:
                limits[key] = value
    # A producer banner alone does not establish a machine's timing dialect.
    return (OrcaTimingPolicy(flavor, limits)
            if flavor in {"marlin", "marlin2", "klipper", "reprapfirmware"} else None)


class OrcaMachineStateTracker(MachineStateTracker):
    def __init__(self, policy: OrcaTimingPolicy):
        super().__init__(bambu_compatible=True)
        self.policy = policy
        self.junction_deviation = policy.limits.get("machine_max_junction_deviation", 0.)
        self.state.print_acceleration_mm_s2 = policy.limits.get("machine_max_acceleration_extruding") or 1500.
        self.state.travel_acceleration_mm_s2 = policy.limits.get("machine_max_acceleration_travel") or 1250.
        self.state.retract_acceleration_mm_s2 = policy.limits.get("machine_max_acceleration_retracting") or 1500.
        self.state.minimum_extruding_feedrate_mm_s = policy.limits.get("machine_min_extruding_rate")
        self.state.minimum_travel_feedrate_mm_s = policy.limits.get("machine_min_travel_rate")
        for axis in "xyze":
            setattr(self.state, f"maximum_acceleration_{axis}_mm_s2", policy.limits.get(f"machine_max_acceleration_{axis}"))
            setattr(self.state, f"maximum_feedrate_{axis}_mm_s", policy.limits.get(f"machine_max_speed_{axis}"))
            setattr(self.state, f"jerk_{axis}_mm_s", policy.limits.get(f"machine_max_jerk_{axis}"))
        self._classic_jerks = {
            axis: getattr(self.state, f"jerk_{axis}_mm_s") for axis in "xyze"
        }
        self._apply_junction_deviation()

    def _apply_junction_deviation(self):
        if not self.policy.uses_junction_deviation or self.junction_deviation <= 0:
            return
        acceleration = self.state.print_acceleration_mm_s2 or 1500.
        for axis in "xyze":
            cap = getattr(self.state, f"maximum_acceleration_{axis}_mm_s2")
            effective = min(acceleration, cap) if cap else acceleration
            setattr(self.state, f"jerk_{axis}_mm_s", math.sqrt(2.5 * self.junction_deviation * effective))

    def process_line(self, parsed):
        if parsed.command == "M4899" and parsed.parameters.get("T") == 3:
            return None
        if parsed.command == "M205" and "J" in parsed.parameters:
            self.junction_deviation = parsed.parameters["J"] * self.state.unit_scale_mm
        if parsed.command == "M205":
            # JD is a derived motion limit, not a replacement for the stored
            # classic jerk. Disabling JD must restore the last explicit limits.
            for axis, jerk in self._classic_jerks.items():
                setattr(self.state, f"jerk_{axis}_mm_s", jerk)
        retract_acceleration = self.state.retract_acceleration_mm_s2
        event = super().process_line(parsed)
        if parsed.command == "SET_VELOCITY_LIMIT":
            self.state.retract_acceleration_mm_s2 = retract_acceleration
            parameters = parsed.parameters
            if "SQUARE_CORNER_VELOCITY" in parameters:
                jerk = parameters["SQUARE_CORNER_VELOCITY"] * self.state.unit_scale_mm
                for axis in "xy":
                    self._classic_jerks[axis] = jerk
                    setattr(self.state, f"jerk_{axis}_mm_s", jerk)
            if "VELOCITY" in parameters:
                for axis in "xy":
                    setattr(self.state, f"maximum_feedrate_{axis}_mm_s",
                            parameters["VELOCITY"] * self.state.unit_scale_mm)
        if parsed.command == "M205":
            self._classic_jerks = {
                axis: getattr(self.state, f"jerk_{axis}_mm_s") for axis in "xyze"
            }
        if parsed.command in {"M204", "SET_VELOCITY_LIMIT"}:
            for category, key in (("print", "extruding"), ("travel", "travel"), ("retract", "retracting")):
                cap = self.policy.limits.get(f"machine_max_acceleration_{key}")
                field = f"{category}_acceleration_mm_s2"
                if cap:
                    setattr(self.state, field, min(getattr(self.state, field) or cap, cap))
        if parsed.command in {"M201", "M204", "M205", "SET_VELOCITY_LIMIT"}:
            self._apply_junction_deviation()
        return event


def orca_junction_speed(previous, current, previous_speed, current_speed,
                        previous_safe, current_safe):
    if min(previous_speed, current_speed) <= MOVEMENT_EPSILON:
        return current_safe
    shared_speed = min(previous_speed, current_speed)
    exiting = _bambu_axis_feedrates(previous, shared_speed)
    entering = _bambu_axis_feedrates(current, current_speed)
    # Orca evaluates commanded velocity changes, including unequal incoming
    # and outgoing feedrates, rather than just a normalized direction change.
    changes = [abs(a-b) for a, b in zip(exiting[:3], entering[:3])]
    factor = 1.
    for axis, limit in enumerate((current.jerk_x_mm_s, current.jerk_y_mm_s, current.jerk_z_mm_s)):
        if limit is not None and changes[axis] > limit:
            factor *= limit / changes[axis]
            changes = [change * factor for change in changes]
    before, after = exiting[3] * factor, entering[3] * factor
    extrusion_change = abs(before-after) if before*after > 0 else max(abs(before), abs(after))
    if current.jerk_e_mm_s is not None and extrusion_change > current.jerk_e_mm_s:
        factor *= current.jerk_e_mm_s / extrusion_change
    speed = shared_speed * factor
    return current_safe if min(previous_safe, current_safe) > .99 * speed else speed


def plan_orca_run(movements, *, start_speed=0., previous=None, cache=None):
    return plan_window(movements, junction_speed=orca_junction_speed,
                       start_speed=start_speed, previous=previous, cache=cache)


class OrcaMotionTimingPlanner(MotionTimingPlanner):
    def __init__(self):
        super().__init__(bambu_compatible=True, refresh_threshold_movements=256)

    def _planned_pending(self):
        movements = [event for event in self._pending_events if self._is_plannable(event)]
        planned = iter(plan_orca_run(movements, start_speed=self._start_speed_mm_s,
                                    previous=self._previous_physical_movement, cache=self._kinematics_cache))
        return [next(planned) if self._is_plannable(event) else event for event in self._pending_events]
